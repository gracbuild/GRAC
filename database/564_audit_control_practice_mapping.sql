-- =====================================================================
-- 5. The pickers' lists: the organization's active practices and
--    practice instances (controls come from the 534 statement tree).
-- =====================================================================
CREATE OR ALTER PROCEDURE grac_practice.sp_org_assurance_mapping_options
    @organization_id BIGINT
AS
BEGIN
    SET NOCOUNT ON;
    IF @organization_id IS NULL
        THROW 53602, 'organization_id is required.', 1;

    SELECT p.practice_id   AS Id,
           p.practice_code AS Code,
           p.practice_name AS Name,
           (SELECT COUNT(*) FROM grac_practice.practice_instance pi
             WHERE pi.practice_id = p.practice_id
               AND pi.organization_id = @organization_id
               AND pi.status = N'Active') AS InstanceCount
      FROM grac_practice.practice p
     WHERE p.organization_id = @organization_id
       AND p.status = N'Active'
     ORDER BY p.practice_code, p.practice_name;

    SELECT pi.practice_instance_id AS Id,
           pi.instance_code        AS Code,
           pi.instance_name        AS Name,
           pi.practice_id          AS PracticeId,
           p.practice_code         AS PracticeCode
      FROM grac_practice.practice_instance pi
      LEFT JOIN grac_practice.practice p ON p.practice_id = pi.practice_id
     WHERE pi.organization_id = @organization_id
       AND pi.status = N'Active'
     ORDER BY p.practice_code, pi.instance_code, pi.instance_name;
END
GO

-- =====================================================================
-- 2. fn_org_assurance_setup_steps (548 body) + the optional mapping step
-- =====================================================================
CREATE OR ALTER FUNCTION grac_practice.fn_org_assurance_setup_steps
(
    @organization_id BIGINT,
    @version_id      BIGINT
)
RETURNS TABLE
AS
RETURN
    WITH c AS (
        SELECT
            (SELECT COUNT(*)
               FROM grac_practice.org_assurance_scope_group g
              WHERE g.org_assurance_definition_version_id = @version_id
                AND g.organization_id = @organization_id
                AND g.is_active = 1)                                  AS scope_groups,
            (SELECT COUNT(*)
               FROM grac_practice.org_assurance_definition_question_set q
              WHERE q.org_assurance_definition_version_id = @version_id
                AND q.organization_id = @organization_id
                AND q.is_active = 1)                                  AS question_sets,
            (SELECT COUNT(*)
               FROM grac_practice.org_assurance_workflow_config w
              WHERE w.org_assurance_definition_version_id = @version_id
                AND w.organization_id = @organization_id
                AND w.is_active = 1)                                  AS workflow_cfg,
            (SELECT COUNT(*)
               FROM grac_practice.org_assurance_workflow_stage st
               JOIN grac_practice.org_assurance_workflow_config w
                    ON w.org_assurance_workflow_config_id = st.org_assurance_workflow_config_id
              WHERE w.org_assurance_definition_version_id = @version_id
                AND w.organization_id = @organization_id
                AND w.is_active = 1
                AND st.is_active = 1)                                 AS workflow_stage,
            (SELECT COUNT(*)
               FROM grac_practice.org_assurance_scoring_config sc
              WHERE sc.org_assurance_definition_version_id = @version_id
                AND sc.organization_id = @organization_id
                AND sc.is_active = 1)                                 AS scoring_cfg,
            (SELECT COUNT(*)
               FROM grac_practice.org_assurance_scoring_band b
               JOIN grac_practice.org_assurance_scoring_config sc
                    ON sc.org_assurance_scoring_config_id = b.org_assurance_scoring_config_id
              WHERE sc.org_assurance_definition_version_id = @version_id
                AND sc.organization_id = @organization_id
                AND sc.is_active = 1
                AND b.is_active  = 1)                                 AS scoring_band,
            -- 541: a scoring config is complete when it has what its model
            -- type uses (087 sp_org_assurance_scoring_model_type_list):
            --   thresholds (SupportsThreshold): PASS_FAIL, WEIGHTED,
            --     PERCENTAGE, CUSTOM -> a Pass Threshold;
            --   bands (SupportsBands): RISK_BASED, MATURITY_BASED,
            --     PERCENTAGE, CUSTOM -> at least one active band.
            -- Before 541 every type needed bands, so a Weighted or Pass /
            -- Fail scoring (thresholds only) never left "In progress".
            (SELECT COUNT(*)
               FROM grac_practice.org_assurance_scoring_config sc
              WHERE sc.org_assurance_definition_version_id = @version_id
                AND sc.organization_id = @organization_id
                AND sc.is_active = 1
                AND (   (sc.scoring_model_type IN (N'PASS_FAIL', N'WEIGHTED', N'PERCENTAGE', N'CUSTOM')
                         AND sc.pass_threshold IS NOT NULL)
                     OR (sc.scoring_model_type IN (N'RISK_BASED', N'MATURITY_BASED', N'PERCENTAGE', N'CUSTOM')
                         AND EXISTS (SELECT 1
                                       FROM grac_practice.org_assurance_scoring_band b
                                      WHERE b.org_assurance_scoring_config_id = sc.org_assurance_scoring_config_id
                                        AND b.is_active = 1))))         AS scoring_ready,
            -- 564: Control and Practice Mapping (optional step)
            (SELECT COUNT(*)
               FROM grac_practice.org_assurance_definition_mapping m
              WHERE m.org_assurance_definition_version_id = @version_id
                AND m.organization_id = @organization_id
                AND m.is_active = 1)                                  AS mappings
            -- 548: no Trigger step -- executions start from plan slots (546);
            -- nothing runs an audit from a trigger.
            -- 545: no Scope Resolution step -- the scope is resolved when
            -- an execution is created (sp_org_assurance_execution_materialize).
    )
    SELECT x.StepOrder, x.StepKey, x.StepName, x.IsConfiguration, x.ItemCount, x.Status
    FROM c
    CROSS APPLY (VALUES
        (1, N'details',          N'Audit Details',    CAST(0 AS BIT), 1,
            N'Completed'),
        (2, N'scope',            N'Scope Builder',    CAST(1 AS BIT), c.scope_groups,
            CASE WHEN c.scope_groups  > 0 THEN N'Completed' ELSE N'NotConfigured' END),
        -- 564: optional (spec 4.2.2 "allow"): not a configuration step for
        -- the review gate or the list's count; Optional until something is
        -- mapped.
        (3, N'mapping',          N'Control and Practice Mapping', CAST(0 AS BIT), c.mappings,
            CASE WHEN c.mappings > 0 THEN N'Completed' ELSE N'Optional' END),
        (4, N'questions',        N'Question Sets',    CAST(1 AS BIT), c.question_sets,
            CASE WHEN c.question_sets > 0 THEN N'Completed' ELSE N'NotConfigured' END),
        (5, N'workflow',         N'Workflow',         CAST(1 AS BIT), c.workflow_stage,
            CASE WHEN c.workflow_stage > 0 THEN N'Completed'
                 WHEN c.workflow_cfg   > 0 THEN N'InProgress'
                 ELSE N'NotConfigured' END),
        (6, N'scoring',          N'Scoring',          CAST(1 AS BIT),
            CASE WHEN c.scoring_band > 0 THEN c.scoring_band ELSE c.scoring_ready END,
            CASE WHEN c.scoring_ready > 0 THEN N'Completed'
                 WHEN c.scoring_cfg  > 0 THEN N'InProgress'
                 ELSE N'NotConfigured' END)
    ) AS x(StepOrder, StepKey, StepName, IsConfiguration, ItemCount, Status);
GO

-- =====================================================================
-- 3. sp_org_assurance_definition_submit (537 body): the gate reads
--    IsConfiguration, so an optional step never blocks the review
-- =====================================================================
CREATE OR ALTER PROCEDURE grac_practice.sp_org_assurance_definition_submit
    @organization_id BIGINT,
    @definition_id   BIGINT,
    @reason_text     NVARCHAR(1000) = NULL,
    @actor           NVARCHAR(100)  = 'system'
AS
BEGIN
    SET NOCOUNT ON;

    -- 537: an audit goes for review only once it is configured -- Scope
    -- and Question Sets (Audit Definition) and Workflow, Scoring, Trigger
    -- and Scope Resolution (Audit Configuration), all Completed for the
    -- current version. Ownership, status and the rest stay with the
    -- transition procedure (a missing / foreign audit skips this check
    -- and fails there with its own error).
    DECLARE @version_id BIGINT, @missing NVARCHAR(400);
    SELECT @version_id = d.current_version_id
      FROM grac_practice.org_assurance_definition d
     WHERE d.org_assurance_definition_id = @definition_id
       AND d.organization_id = @organization_id
       AND d.is_active = 1;

    IF @version_id IS NOT NULL
    BEGIN
        SELECT @missing = STRING_AGG(f.StepName, N', ') WITHIN GROUP (ORDER BY f.StepOrder)
          FROM grac_practice.fn_org_assurance_setup_steps(@organization_id, @version_id) f
         WHERE f.IsConfiguration = 1      -- 564: an optional step (mapping) never blocks
           AND f.Status <> N'Completed';

        IF @missing IS NOT NULL
        BEGIN
            DECLARE @msg NVARCHAR(2048) =
                N'Complete the audit configuration before submitting it for review. Not complete: '
                + @missing + N'.';
            THROW 53612, @msg, 1;
        END
    END

    EXEC grac_practice.sp_org_assurance_definition_transition
        @organization_id    = @organization_id,
        @definition_id      = @definition_id,
        @expected_from_code = N'Draft',
        @to_code            = N'UnderReview',
        @action_code        = N'SUBMIT',
        @reason_text        = @reason_text,
        @actor              = @actor;
END
GO

