-- 2. sp_org_assurance_execution_live_scope (556 body) + #scope_review_pi
-- =====================================================================
CREATE OR ALTER PROCEDURE grac_practice.sp_org_assurance_execution_live_scope
    @organization_id BIGINT,
    @execution_id    BIGINT,
    @actor           NVARCHAR(100) = 'system',
    @mode            NVARCHAR(20)  = N'SCOPE'      -- 556: SCOPE / ASSURANCE
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;
    IF @organization_id IS NULL OR @execution_id IS NULL
        THROW 54009, 'organization_id and execution_id are required.', 1;

    DECLARE @def BIGINT, @ver BIGINT, @item BIGINT, @frozen DATETIME2;
    SELECT @def    = e.org_assurance_definition_id,
           @ver    = e.org_assurance_definition_version_id,
           @item   = e.org_assurance_plan_item_id,
           @frozen = e.scope_frozen_at
      FROM grac_practice.org_assurance_execution e
     WHERE e.org_assurance_execution_id = @execution_id
       AND e.organization_id = @organization_id
       AND e.is_active = 1;
    IF @def IS NULL
        THROW 54010, 'Execution not found or not accessible in this organization.', 1;

    DECLARE @ents TABLE (dimension_code NVARCHAR(60) NULL, dimension_name NVARCHAR(160) NULL,
                         entity_id BIGINT NULL, entity_code NVARCHAR(120) NULL, entity_name NVARCHAR(240) NULL);

    IF @frozen IS NOT NULL
        INSERT INTO @ents (dimension_code, dimension_name, entity_id, entity_code, entity_name)
        SELECT ee.dimension_code, ee.dimension_name, ee.entity_id, ee.entity_code, ee.entity_name
          FROM grac_practice.org_assurance_execution_entity ee
         WHERE ee.org_assurance_execution_id = @execution_id
           AND ee.organization_id = @organization_id
           AND ee.is_active = 1;
    ELSE
    BEGIN
        DECLARE @branch BIGINT = (SELECT assigned_branch_id FROM grac_practice.org_assurance_plan_item
                                   WHERE org_assurance_plan_item_id = @item);
        DECLARE @res BIGINT;

        BEGIN TRAN;
        EXEC grac_practice.sp_org_assurance_scope_resolve
             @organization_id    = @organization_id,
             @definition_id      = @def,
             @version_id         = @ver,
             @resolution_purpose = N'PREVIEW',
             @execution_id       = NULL,
             @actor              = @actor,
             @resolution_id_out  = @res OUTPUT;
        IF @branch IS NOT NULL
            EXEC grac_practice.sp_org_assurance_scope_resolution_narrow_location
                 @organization_id = @organization_id,
                 @resolution_id   = @res,
                 @location_id     = @branch;
        INSERT INTO @ents (dimension_code, dimension_name, entity_id, entity_code, entity_name)
        SELECT DISTINCT r.dimension_code, r.dimension_name, r.entity_id, r.entity_code, r.entity_name
          FROM grac_practice.org_assurance_scope_resolution_entity r
         WHERE r.org_assurance_scope_resolution_id = @res;
        ROLLBACK;   -- live: nothing the resolver wrote is kept
    END

    -- 563: a caller that created #scope_review_pi (the scope discovery of
    -- an engagement) gets the items there instead of a result set.
    IF OBJECT_ID('tempdb..#scope_review_pi') IS NOT NULL AND ISNULL(@mode, N'SCOPE') <> N'ASSURANCE'
    BEGIN
        INSERT INTO #scope_review_pi (dimension_code, entity_id)
        SELECT DISTINCT dimension_code, entity_id FROM @ents WHERE entity_id IS NOT NULL;
        RETURN;
    END

    IF ISNULL(@mode, N'SCOPE') <> N'ASSURANCE'
    BEGIN
        SELECT dimension_code AS DimensionCode, dimension_name AS DimensionName,
               entity_id AS EntityId, entity_code AS EntityCode, entity_name AS EntityName
          FROM @ents
         ORDER BY dimension_code, entity_name, entity_code;
        RETURN;
    END

    -- -----------------------------------------------------------------
    -- 556: Continuous Assurance (decision 4, 2026-11-14)
    -- Each scope item -> its practice instances:
    --   PRACTICE_INSTANCE   directly;
    --   ASSET, DEPARTMENT, VENDOR, APPLICATION, PROCESS, BRANCH (Location)
    --                       through practice_dependency_resolution (the
    --                       Operationalize resolution, active rows);
    --   ASSET_CATEGORY      through its assets, then as ASSET.
    -- -> their active Execution / Assurance obligations (the scheduled
    --    ones, 338 / 449) -> implementation status and the last task raised
    --    for the obligation (schedule_occurrence_task -> practice_task).
    -- -----------------------------------------------------------------
    DECLARE @map TABLE (dimension_code NVARCHAR(60) PRIMARY KEY, dependency_type_code NVARCHAR(60) NOT NULL);
    INSERT INTO @map VALUES
        (N'ASSET', N'Asset'), (N'DEPARTMENT', N'Department'), (N'VENDOR', N'Vendor'),
        (N'APPLICATION', N'Application'), (N'PROCESS', N'Process'), (N'BRANCH', N'Location');

    DECLARE @link TABLE (dimension_code NVARCHAR(60) NULL, entity_id BIGINT NULL,
                         practice_instance_id BIGINT NOT NULL, via NVARCHAR(60) NOT NULL);

    -- directly
    INSERT INTO @link (dimension_code, entity_id, practice_instance_id, via)
    SELECT e.dimension_code, e.entity_id, e.entity_id, N'Direct'
      FROM @ents e
     WHERE e.dimension_code = N'PRACTICE_INSTANCE' AND e.entity_id IS NOT NULL;

    -- through the Operationalize resolution
    INSERT INTO @link (dimension_code, entity_id, practice_instance_id, via)
    SELECT DISTINCT e.dimension_code, e.entity_id, r.practice_instance_id, dt.dependency_type_name
      FROM @ents e
      JOIN @map m ON m.dimension_code = e.dimension_code
      JOIN grac_practice.dependency_type_master dt
           ON dt.dependency_type_code = m.dependency_type_code
      JOIN grac_practice.practice_dependency_resolution r
           ON r.dependency_type_id     = dt.dependency_type_id
          AND r.resolved_dependency_id = e.entity_id
          AND r.organization_id        = @organization_id
          AND r.is_active              = 1;

    -- asset category -> its assets -> as ASSET
    INSERT INTO @link (dimension_code, entity_id, practice_instance_id, via)
    SELECT DISTINCT e.dimension_code, e.entity_id, r.practice_instance_id, N'Asset: ' + a.asset_name
      FROM @ents e
      JOIN grac_practice.organization_dependency_asset a
           ON a.asset_category_id = e.entity_id
          AND a.organization_id   = @organization_id
      JOIN grac_practice.dependency_type_master dt
           ON dt.dependency_type_code = N'Asset'
      JOIN grac_practice.practice_dependency_resolution r
           ON r.dependency_type_id     = dt.dependency_type_id
          AND r.resolved_dependency_id = a.asset_id
          AND r.organization_id        = @organization_id
          AND r.is_active              = 1
     WHERE e.dimension_code = N'ASSET_CATEGORY';

    DECLARE @detail TABLE (
        dimension_code NVARCHAR(60) NULL, dimension_name NVARCHAR(160) NULL,
        entity_id BIGINT NULL, entity_code NVARCHAR(120) NULL, entity_name NVARCHAR(240) NULL,
        practice_instance_id BIGINT NULL, instance_code NVARCHAR(100) NULL, instance_name NVARCHAR(300) NULL,
        via NVARCHAR(400) NULL,
        obligation_id BIGINT NULL, obligation_name NVARCHAR(500) NULL, obligation_type NVARCHAR(60) NULL,
        frequency NVARCHAR(120) NULL,
        status_code NVARCHAR(60) NULL, status_name NVARCHAR(100) NULL,
        task_id BIGINT NULL, task_number NVARCHAR(60) NULL, task_status_code NVARCHAR(60) NULL,
        task_status_name NVARCHAR(120) NULL, task_due DATE NULL);

    INSERT INTO @detail
    SELECT e.dimension_code, e.dimension_name, e.entity_id, e.entity_code, e.entity_name,
           pi.practice_instance_id, pi.instance_code, pi.instance_name,
           l.via,
           pio.practice_instance_obligation_id, pio.obligation_name, pio.obligation_type_code,
           CASE WHEN pio.obligation_type_code = N'Assurance' THEN pio.assurance_frequency ELSE pio.execution_frequency END,
           ism.status_code, ism.status_name,
           lt.task_id, CONVERT(NVARCHAR(60), lt.task_number), lt.status_code, lt.status_name, lt.occurrence_date
      FROM @ents e
      LEFT JOIN @link l
             ON l.dimension_code = e.dimension_code AND l.entity_id = e.entity_id
      LEFT JOIN grac_practice.practice_instance pi
             ON pi.practice_instance_id = l.practice_instance_id
            AND pi.organization_id = @organization_id
            AND pi.status = N'Active'
      LEFT JOIN grac_practice.practice_instance_obligation pio
             ON pio.practice_instance_id = pi.practice_instance_id
            AND pio.status = N'Active'
            AND pio.obligation_type_code IN (N'Execution', N'Assurance')
      LEFT JOIN grac_practice.implementation_status_master ism
             ON ism.implementation_status_id = pio.implementation_status_id
      OUTER APPLY (
          SELECT TOP 1 t.task_id, t.task_number, es.status_code, es.status_name, x.occurrence_date
            FROM grac_practice.schedule_occurrence_task x
            JOIN grac_practice.practice_task t ON t.task_id = x.task_id
            LEFT JOIN grac_practice.entity_status_master es
                   ON es.entity_status_id = t.current_status_id
           WHERE x.practice_instance_obligation_id = pio.practice_instance_obligation_id
             AND x.task_id IS NOT NULL
           ORDER BY x.occurrence_date DESC, x.occurrence_task_id DESC) lt;

    -- Result 1: the summary -- every obligation counted once, however many
    -- scope items bring it in.
    ;WITH ob AS (
        SELECT DISTINCT obligation_id, ISNULL(status_name, N'Not set') AS status_name,
               ISNULL(task_status_name, N'No task yet') AS task_status_name
          FROM @detail WHERE obligation_id IS NOT NULL
    )
    SELECT N'Totals' AS SummaryKind, N'Scope items' AS Label,
           (SELECT COUNT(*) FROM @ents) AS ItemCount, 1 AS SortOrder
    UNION ALL SELECT N'Totals', N'Practice instances',
           (SELECT COUNT(DISTINCT practice_instance_id) FROM @detail WHERE practice_instance_id IS NOT NULL), 2
    UNION ALL SELECT N'Totals', N'Obligations', (SELECT COUNT(*) FROM ob), 3
    UNION ALL SELECT N'Totals', N'Scope items with no practice instance',
           (SELECT COUNT(*) FROM @ents e
             WHERE NOT EXISTS (SELECT 1 FROM @detail d
                                WHERE d.dimension_code = e.dimension_code
                                  AND d.entity_id = e.entity_id
                                  AND d.practice_instance_id IS NOT NULL)), 4
    UNION ALL SELECT N'ObligationStatus', status_name, COUNT(*), 10 FROM ob GROUP BY status_name
    UNION ALL SELECT N'LastTaskStatus', task_status_name, COUNT(*), 20 FROM ob GROUP BY task_status_name
    ORDER BY SortOrder, Label;

    -- Result 2: the detail.
    SELECT dimension_code AS DimensionCode, dimension_name AS DimensionName,
           entity_id AS EntityId, entity_code AS EntityCode, entity_name AS EntityName,
           practice_instance_id AS PracticeInstanceId, instance_code AS InstanceCode,
           instance_name AS InstanceName, via AS Via,
           obligation_id AS ObligationId, obligation_name AS ObligationName,
           obligation_type AS ObligationType, frequency AS Frequency,
           status_code AS ObligationStatusCode, status_name AS ObligationStatusName,
           task_id AS LastTaskId, task_number AS LastTaskNumber,
           task_status_code AS LastTaskStatusCode, task_status_name AS LastTaskStatusName,
           task_due AS LastTaskDueDate
      FROM @detail
     ORDER BY dimension_code, entity_name, instance_name, obligation_name;
END
GO

-- =====================================================================
-- 3. sp_org_assurance_scope_discover (562 body) + @execution_id
-- =====================================================================
CREATE OR ALTER PROCEDURE grac_practice.sp_org_assurance_scope_discover
    @organization_id BIGINT,
    @definition_id   BIGINT,
    @version_id      BIGINT = NULL,     -- default: the current version
    @execution_id    BIGINT = NULL      -- 563: an engagement's scope (Step 3)
AS
BEGIN
    SET NOCOUNT ON;

    IF @organization_id IS NULL OR @definition_id IS NULL
        THROW 53602, 'organization_id and definition_id are required.', 1;

    DECLARE @def_org BIGINT, @current_version_id BIGINT;
    SELECT @def_org = d.organization_id, @current_version_id = d.current_version_id
    FROM grac_practice.org_assurance_definition d
    WHERE d.org_assurance_definition_id = @definition_id AND d.is_active = 1;
    IF @def_org IS NULL THROW 53606, 'Definition not found.', 1;
    IF @def_org <> @organization_id THROW 53607, 'Definition belongs to a different organization.', 1;
    -- 563: for an engagement, its own definition version.
    IF @execution_id IS NOT NULL
    BEGIN
        DECLARE @exec_version_id BIGINT;
        SELECT @exec_version_id = e.org_assurance_definition_version_id
          FROM grac_practice.org_assurance_execution e
         WHERE e.org_assurance_execution_id  = @execution_id
           AND e.organization_id             = @organization_id
           AND e.org_assurance_definition_id = @definition_id
           AND e.is_active = 1;
        IF @exec_version_id IS NULL
            THROW 54010, 'Execution not found or not accessible in this organization.', 1;
        SET @version_id = @exec_version_id;
    END
    IF @version_id IS NULL SET @version_id = @current_version_id;
    IF @version_id IS NULL THROW 53611, 'Definition has no current version.', 1;

    DECLARE @active_rs INT = (SELECT TOP 1 record_status_id FROM grac_practice.record_status_master
                               WHERE status_code = N'ACTIVE' OR status_name = N'Active'
                               ORDER BY record_status_id);

    -- Categories, in display order.
    CREATE TABLE #cat (category_code NVARCHAR(40) PRIMARY KEY, category_name NVARCHAR(80), display_order INT);
    INSERT #cat VALUES
        (N'PRACTICE_INSTANCE', N'Practice Instances', 1),
        (N'PRACTICE',          N'Practices',          2),
        (N'CONTROL_STATEMENT', N'Control Statements', 3),
        (N'RISK',              N'Risks',              4),
        (N'GAP',               N'Gaps',               5),
        (N'EXCEPTION',         N'Exceptions',         6),
        (N'ASSET',             N'Assets',             7),
        (N'VENDOR',            N'Vendors',            8);

    -- The version's subjects (explicit picks; a NOT / include-all rule from
    -- the removed Advanced mode is not discovered).
    CREATE TABLE #subj (dimension_code NVARCHAR(60), entity_id BIGINT, entity_name NVARCHAR(240),
                        dependency_type_id INT NULL, dependency_type_name NVARCHAR(120) NULL);
    INSERT #subj (dimension_code, entity_id, entity_name, dependency_type_id, dependency_type_name)
    SELECT DISTINCT dm.dimension_code, v.dimension_entity_id,
           ISNULL(v.dimension_entity_name, N'#' + CAST(v.dimension_entity_id AS NVARCHAR(30))),
           dt.dependency_type_id, dt.dependency_type_name
    FROM grac_practice.org_assurance_scope_group g
    JOIN grac_practice.org_assurance_scope_condition c
         ON c.scope_group_id = g.scope_group_id AND c.is_active = 1 AND c.is_not = 0
    JOIN grac_practice.org_assurance_scope_dimension_master dm ON dm.dimension_id = c.dimension_id
    JOIN grac_practice.org_assurance_scope_condition_value v
         ON v.scope_condition_id = c.scope_condition_id AND v.is_active = 1 AND v.dimension_entity_id IS NOT NULL
    OUTER APPLY grac_practice.fn_org_assurance_dep_type(dm.dimension_code) dt
    WHERE g.org_assurance_definition_version_id = @version_id
      AND g.organization_id = @organization_id
      AND g.is_active = 1;

    -- Practice instances in scope, with why.
    CREATE TABLE #pi (practice_instance_id BIGINT, reason NVARCHAR(400));
    INSERT #pi (practice_instance_id, reason)
    SELECT DISTINCT r.practice_instance_id,
           N'Depends on ' + s.dependency_type_name + N' "' + s.entity_name + N'"'
    FROM #subj s
    JOIN grac_practice.practice_dependency_resolution r
         ON r.dependency_type_id = s.dependency_type_id
        AND r.resolved_dependency_id = s.entity_id
        AND r.organization_id = @organization_id
        AND r.is_active = 1
    JOIN grac_practice.practice_instance pi
         ON pi.practice_instance_id = r.practice_instance_id AND pi.status = N'Active'
    WHERE s.dependency_type_id IS NOT NULL;

    INSERT #pi (practice_instance_id, reason)
    SELECT DISTINCT si.PracticeInstanceId, N'Under control statement "' + s.entity_name + N'"'
    FROM #subj s
    JOIN grac_practice.fn_org_scope_statement_instance(@organization_id) si ON si.StatementId = s.entity_id
    WHERE s.dimension_code = N'SOURCE_STATEMENT';

    INSERT #pi (practice_instance_id, reason)
    SELECT DISTINCT s.entity_id, N'Picked directly'
    FROM #subj s
    WHERE s.dimension_code = N'PRACTICE_INSTANCE';

    -- 563: an engagement's review covers the instances of ITS scope -- the
    -- frozen entities, or the scope now narrowed to its Branch -- read
    -- through sp_org_assurance_execution_live_scope, so Freeze, View Scope,
    -- Continuous Assurance and this review never disagree.
    IF @execution_id IS NOT NULL
    BEGIN
        CREATE TABLE #scope_review_pi (dimension_code NVARCHAR(60) NULL, entity_id BIGINT NULL);
        EXEC grac_practice.sp_org_assurance_execution_live_scope
             @organization_id = @organization_id,
             @execution_id    = @execution_id,
             @actor           = N'system';
        DELETE p FROM #pi p
         WHERE NOT EXISTS (SELECT 1 FROM #scope_review_pi s
                            WHERE s.dimension_code = N'PRACTICE_INSTANCE'
                              AND s.entity_id      = p.practice_instance_id);
        INSERT #pi (practice_instance_id, reason)
        SELECT DISTINCT s.entity_id, N'In the engagement scope'
          FROM #scope_review_pi s
         WHERE s.dimension_code = N'PRACTICE_INSTANCE'
           AND NOT EXISTS (SELECT 1 FROM #pi p WHERE p.practice_instance_id = s.entity_id);
    END

    CREATE TABLE #inst (practice_instance_id BIGINT PRIMARY KEY, practice_id BIGINT, instance_code NVARCHAR(100),
                        instance_name NVARCHAR(300), status NVARCHAR(30), reason NVARCHAR(MAX));
    INSERT #inst
    SELECT pi.practice_instance_id, pi.practice_id, pi.instance_code, pi.instance_name, pi.status,
           STRING_AGG(CONVERT(NVARCHAR(MAX), x.reason), N'; ')
    FROM (SELECT DISTINCT practice_instance_id, reason FROM #pi) x
    JOIN grac_practice.practice_instance pi
         ON pi.practice_instance_id = x.practice_instance_id AND pi.organization_id = @organization_id
    GROUP BY pi.practice_instance_id, pi.practice_id, pi.instance_code, pi.instance_name, pi.status;

    -- Practices of those instances.
    CREATE TABLE #prac (practice_id BIGINT PRIMARY KEY, practice_code NVARCHAR(100), practice_name NVARCHAR(300),
                        status NVARCHAR(30), instance_codes NVARCHAR(MAX));
    INSERT #prac
    SELECT p.practice_id, p.practice_code, p.practice_name, p.status,
           STRING_AGG(CONVERT(NVARCHAR(MAX), i.instance_code), N', ')
    FROM #inst i
    JOIN grac_practice.practice p ON p.practice_id = i.practice_id
    GROUP BY p.practice_id, p.practice_code, p.practice_name, p.status;

    CREATE TABLE #out (category_code NVARCHAR(40), record_id BIGINT, record_code NVARCHAR(120),
                       record_name NVARCHAR(400), status NVARCHAR(60), reason NVARCHAR(MAX));

    -- Practice instances
    INSERT #out SELECT N'PRACTICE_INSTANCE', practice_instance_id, instance_code, instance_name, status, reason FROM #inst;

    -- Practices
    INSERT #out SELECT N'PRACTICE', practice_id, practice_code, practice_name, status,
                       N'Practice of instance(s) ' + instance_codes FROM #prac;

    -- Control statements: mapped to the instances, or picked as a subject.
    ;WITH st AS (
        SELECT si.StatementId, N'Mapped to instance ' + i.instance_code AS reason
        FROM #inst i
        JOIN grac_practice.fn_org_scope_statement_instance(@organization_id) si ON si.PracticeInstanceId = i.practice_instance_id
        UNION
        SELECT s.entity_id, N'Picked as a subject'
        FROM #subj s WHERE s.dimension_code = N'SOURCE_STATEMENT'
    )
    INSERT #out
    SELECT N'CONTROL_STATEMENT', fs.StatementId, fs.StatementCode, fs.StatementName, NULL,
           STRING_AGG(CONVERT(NVARCHAR(MAX), st.reason), N'; ')
    FROM st
    JOIN grac_practice.fn_org_scope_statement(@organization_id) fs ON fs.StatementId = st.StatementId
    GROUP BY fs.StatementId, fs.StatementCode, fs.StatementName;

    -- Risks: impact a subject (Risk -> Impact Details), or linked to a
    -- practice in scope (treatment mapping, or the risk's own practice).
    ;WITH rk AS (
        SELECT m.risk_register_id,
               N'Impacts ' + s.dependency_type_name + N' "' + s.entity_name + N'"' AS reason
        FROM #subj s
        JOIN grac_practice.risk_dependency_map m
             ON m.dependency_type_id = s.dependency_type_id
            AND m.dependency_object_id = s.entity_id
            AND m.organization_id = @organization_id
            AND m.record_status_id = @active_rs
        WHERE s.dependency_type_id IS NOT NULL
        UNION
        SELECT rpm.risk_register_id, N'Linked to practice ' + p.practice_code
        FROM #prac p
        JOIN grac_practice.risk_practice_map rpm
             ON rpm.practice_id = p.practice_id AND rpm.organization_id = @organization_id
            AND rpm.record_status_id = @active_rs
        UNION
        SELECT rr.risk_register_id, N'Linked to practice ' + p.practice_code
        FROM #prac p
        JOIN grac_practice.risk_register rr
             ON rr.linked_practice_id = p.practice_id AND rr.organization_id = @organization_id
    )
    INSERT #out
    SELECT N'RISK', rr.risk_register_id, NULL, rr.risk_title, rr.status_code,
           STRING_AGG(CONVERT(NVARCHAR(MAX), rk.reason), N'; ')
    FROM rk
    JOIN grac_practice.risk_register rr
         ON rr.risk_register_id = rk.risk_register_id AND rr.organization_id = @organization_id
        AND rr.record_status_id = @active_rs
    GROUP BY rr.risk_register_id, rr.risk_title, rr.status_code;

    -- Gaps (Gap Center) raised against a practice in scope.
    INSERT #out
    SELECT N'GAP', cg.custom_gap_id, NULL, cg.title, cg.status,
           STRING_AGG(CONVERT(NVARCHAR(MAX), N'Raised against practice ' + p.practice_code), N'; ')
    FROM #prac p
    JOIN grac_practice.custom_gap_practice_map gm
         ON gm.practice_id = p.practice_id AND gm.organization_id = @organization_id
        AND gm.record_status_id = @active_rs
    JOIN grac_practice.custom_gap cg
         ON cg.custom_gap_id = gm.custom_gap_id AND cg.organization_id = @organization_id
    GROUP BY cg.custom_gap_id, cg.title, cg.status;

    -- Exceptions raised against a practice in scope.
    INSERT #out
    SELECT N'EXCEPTION', er.exception_request_id, NULL, er.request_title, er.status_code,
           STRING_AGG(CONVERT(NVARCHAR(MAX), N'Raised against practice ' + p.practice_code), N'; ')
    FROM #prac p
    JOIN grac_practice.exception_request_practice ep
         ON ep.practice_id = p.practice_id AND ep.organization_id = @organization_id
        AND ep.record_status_id = @active_rs
    JOIN grac_practice.exception_request er
         ON er.exception_request_id = ep.exception_request_id AND er.organization_id = @organization_id
    GROUP BY er.exception_request_id, er.request_title, er.status_code;

    -- Assets and vendors: picked as a subject, or a dependency of an
    -- instance in scope (Operationalize).
    ;WITH dep AS (
        SELECT UPPER(s.dependency_type_name) AS type_key, s.entity_id AS object_id,
               s.entity_name AS object_name, N'Picked as a subject' AS reason
        FROM #subj s
        WHERE UPPER(s.dependency_type_name) IN (N'ASSET', N'VENDOR')
        UNION
        SELECT UPPER(dt.dependency_type_name), r.resolved_dependency_id, r.resolved_dependency_name,
               N'Instance ' + i.instance_code + N' depends on it'
        FROM #inst i
        JOIN grac_practice.practice_dependency_resolution r
             ON r.practice_instance_id = i.practice_instance_id
            AND r.organization_id = @organization_id AND r.is_active = 1
        JOIN grac_practice.dependency_type_master dt
             ON dt.dependency_type_id = r.dependency_type_id
        WHERE UPPER(dt.dependency_type_name) IN (N'ASSET', N'VENDOR')
    )
    INSERT #out
    SELECT dep.type_key, dep.object_id, NULL, MAX(dep.object_name), NULL,
           STRING_AGG(CONVERT(NVARCHAR(MAX), dep.reason), N'; ')
    FROM dep
    GROUP BY dep.type_key, dep.object_id;

    -- Result 1: categories
    SELECT c.category_code AS CategoryCode,
           c.category_name AS CategoryName,
           c.display_order AS DisplayOrder,
           (SELECT COUNT_BIG(*) FROM #out o WHERE o.category_code = c.category_code) AS ItemCount,
           CAST(ISNULL(sc.is_included, 1) AS BIT) AS IsIncluded
    INTO #res_cat
    FROM #cat c
    LEFT JOIN grac_practice.org_assurance_scope_category sc
           ON sc.org_assurance_definition_version_id = @version_id
          AND sc.category_code = c.category_code
          AND sc.is_active = 1;

    -- 563: a caller that created #scope_review_cat / #scope_review_out
    -- (the engagement's review, its freeze) gets the results there.
    IF OBJECT_ID('tempdb..#scope_review_cat') IS NOT NULL
       AND OBJECT_ID('tempdb..#scope_review_out') IS NOT NULL
    BEGIN
        INSERT #scope_review_cat (category_code, category_name, display_order, item_count, is_included)
        SELECT CategoryCode, CategoryName, DisplayOrder, ItemCount, IsIncluded FROM #res_cat;
        INSERT #scope_review_out (category_code, record_id, record_code, record_name, status, reason)
        SELECT category_code, record_id, record_code, record_name, status, reason FROM #out;
        RETURN;
    END

    SELECT CategoryCode, CategoryName, DisplayOrder, ItemCount, IsIncluded
    FROM #res_cat
    ORDER BY DisplayOrder;

    -- Result 2: records
    SELECT o.category_code AS CategoryCode,
           o.record_id     AS RecordId,
           o.record_code   AS RecordCode,
           o.record_name   AS RecordName,
           o.status        AS Status,
           o.reason        AS Reason
    FROM #out o
    JOIN #cat c ON c.category_code = o.category_code
    ORDER BY c.display_order, o.record_code, o.record_name;
END
GO

-- =====================================================================
-- 4. sp_org_assurance_execution_freeze_scope (555 body) + @review_json
-- =====================================================================
CREATE OR ALTER PROCEDURE grac_practice.sp_org_assurance_execution_freeze_scope
    @organization_id BIGINT,
    @execution_id    BIGINT,
    @employee_id     BIGINT,
    @exclusions_json NVARCHAR(MAX) = NULL,
    @actor           NVARCHAR(100) = 'system',
    @review_json     NVARCHAR(MAX) = NULL   -- 563: Step 3 Review and Confirm
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;
    IF @organization_id IS NULL OR @execution_id IS NULL
        THROW 54009, 'organization_id and execution_id are required.', 1;
    IF @employee_id IS NULL
        THROW 54036, 'Sign in as the assigned auditor to freeze the scope.', 1;

    DECLARE @def BIGINT, @ver BIGINT, @item BIGINT, @owner BIGINT,
            @frozen DATETIME2, @status NVARCHAR(60);
    SELECT @def    = e.org_assurance_definition_id,
           @ver    = e.org_assurance_definition_version_id,
           @item   = e.org_assurance_plan_item_id,
           @owner  = e.owner_employee_id,
           @frozen = e.scope_frozen_at,
           @status = s.status_code
      FROM grac_practice.org_assurance_execution e
      JOIN grac_practice.org_assurance_execution_status_master s
           ON s.org_assurance_execution_status_id = e.execution_status_id
     WHERE e.org_assurance_execution_id = @execution_id
       AND e.organization_id = @organization_id
       AND e.is_active = 1;
    IF @def IS NULL
        THROW 54010, 'Execution not found or not accessible in this organization.', 1;
    IF @frozen IS NOT NULL
        THROW 54031, 'The scope of this execution is already frozen.', 1;
    IF @owner IS NULL OR @owner <> @employee_id
        THROW 54032, 'Only the assigned auditor can freeze the scope.', 1;
    IF @status <> N'Planned'
        THROW 54033, 'The scope can be frozen only while the execution is Planned.', 1;

    DECLARE @excl TABLE (dimension_code NVARCHAR(60) NULL, entity_id BIGINT NULL, reason NVARCHAR(1000) NULL);
    IF @exclusions_json IS NOT NULL AND ISJSON(@exclusions_json) = 1
        INSERT INTO @excl (dimension_code, entity_id, reason)
        SELECT x.dimension_code, x.entity_id, MAX(x.reason)
          FROM (SELECT NULLIF(LTRIM(RTRIM(JSON_VALUE(j.[value], '$.dimensionCode'))), N'') AS dimension_code,
                       TRY_CAST(JSON_VALUE(j.[value], '$.entityId') AS BIGINT)            AS entity_id,
                       LEFT(NULLIF(LTRIM(RTRIM(JSON_VALUE(j.[value], '$.reason'))), N''), 1000) AS reason
                  FROM OPENJSON(@exclusions_json) j) x
         GROUP BY x.dimension_code, x.entity_id;
    IF EXISTS (SELECT 1 FROM @excl WHERE dimension_code IS NULL OR entity_id IS NULL OR reason IS NULL)
        THROW 54034, 'Every excluded item needs a reason.', 1;

    DECLARE @branch BIGINT = (SELECT assigned_branch_id FROM grac_practice.org_assurance_plan_item
                               WHERE org_assurance_plan_item_id = @item);
    DECLARE @res BIGINT, @total BIGINT, @summary NVARCHAR(MAX);

    BEGIN TRAN;

    EXEC grac_practice.sp_org_assurance_scope_resolve
         @organization_id    = @organization_id,
         @definition_id      = @def,
         @version_id         = @ver,
         @resolution_purpose = N'EXECUTION',
         @execution_id       = @execution_id,
         @actor              = @actor,
         @resolution_id_out  = @res OUTPUT;
    IF @branch IS NOT NULL
        EXEC grac_practice.sp_org_assurance_scope_resolution_narrow_location
             @organization_id = @organization_id,
             @resolution_id   = @res,
             @location_id     = @branch;

    IF EXISTS (SELECT 1 FROM @excl x
                WHERE NOT EXISTS (SELECT 1 FROM grac_practice.org_assurance_scope_resolution_entity r
                                   WHERE r.org_assurance_scope_resolution_id = @res
                                     AND r.dimension_code = x.dimension_code
                                     AND r.entity_id      = x.entity_id))
        THROW 54034, 'An excluded item is no longer in the scope. Reload the scope and try again.', 1;

    INSERT INTO grac_practice.org_assurance_execution_scope_exclusion
        (organization_id, org_assurance_execution_id, dimension_code, dimension_name,
         entity_id, entity_code, entity_name, reason, entered_by)
    SELECT @organization_id, @execution_id, x.dimension_code, r.dimension_name,
           x.entity_id, r.entity_code, r.entity_name, x.reason, @actor
      FROM @excl x
      CROSS APPLY (SELECT TOP 1 re.dimension_name, re.entity_code, re.entity_name
                     FROM grac_practice.org_assurance_scope_resolution_entity re
                    WHERE re.org_assurance_scope_resolution_id = @res
                      AND re.dimension_code = x.dimension_code
                      AND re.entity_id      = x.entity_id) r;

    DELETE r
      FROM grac_practice.org_assurance_scope_resolution_entity r
      JOIN @excl x ON x.dimension_code = r.dimension_code AND x.entity_id = r.entity_id
     WHERE r.org_assurance_scope_resolution_id = @res;

    IF NOT EXISTS (SELECT 1 FROM grac_practice.org_assurance_scope_resolution_entity
                    WHERE org_assurance_scope_resolution_id = @res)
        THROW 54035, 'Nothing is left in the scope. Keep at least one item, or cancel the execution.', 1;

    SET @summary = (SELECT dimension_code AS dimensionCode, COUNT(*) AS entityCount
                      FROM grac_practice.org_assurance_scope_resolution_entity
                     WHERE org_assurance_scope_resolution_id = @res
                     GROUP BY dimension_code
                     ORDER BY dimension_code
                       FOR JSON PATH);
    SET @total = (SELECT COUNT_BIG(*) FROM grac_practice.org_assurance_scope_resolution_entity
                   WHERE org_assurance_scope_resolution_id = @res);
    UPDATE grac_practice.org_assurance_scope_resolution
       SET total_entity_count = @total, summary_json = @summary, execution_id = @execution_id
     WHERE org_assurance_scope_resolution_id = @res;

    -- The entities, as materialize copies them.
    INSERT INTO grac_practice.org_assurance_execution_entity(
        org_assurance_execution_id, organization_id,
        dimension_code, dimension_name,
        entity_id, entity_code, entity_name,
        source_group_order, source_condition_order,
        entity_status_code, is_active, entered_by, entered_dt)
    SELECT @execution_id, @organization_id,
           r.dimension_code, r.dimension_name,
           r.entity_id, r.entity_code, r.entity_name,
           r.source_group_order, r.source_condition_order,
           N'NotStarted', 1, @actor, SYSUTCDATETIME()
      FROM grac_practice.org_assurance_scope_resolution_entity r
     WHERE r.org_assurance_scope_resolution_id = @res
       AND r.organization_id = @organization_id;

    UPDATE grac_practice.org_assurance_execution
       SET org_assurance_scope_resolution_id = @res,
           total_entity_count = (SELECT COUNT_BIG(1) FROM grac_practice.org_assurance_execution_entity
                                  WHERE org_assurance_execution_id = @execution_id AND is_active = 1),
           scope_frozen_at    = SYSUTCDATETIME(),
           scope_frozen_by    = @actor,
           updated_by         = @actor,
           updated_dt         = SYSUTCDATETIME()
     WHERE org_assurance_execution_id = @execution_id;

    -- 563: Step 3 Review and Confirm. The related records of the frozen
    -- scope (Step 2 discovery over THIS engagement's instances), with the
    -- auditor's category ticks, unticked records (each with a reason) and
    -- manual items, kept as the engagement's approved scope snapshot.
    -- Immutable: a later change is a new version (phase F).
    -- @review_json: { categories: [{ code, isIncluded }],
    --                 excluded:   [{ categoryCode, recordId, reason }],
    --                 manual:     [{ categoryCode, name, note }] }
    CREATE TABLE #scope_review_cat (category_code NVARCHAR(40) NULL, category_name NVARCHAR(80) NULL,
                                    display_order INT NULL, item_count BIGINT NULL, is_included BIT NULL);
    CREATE TABLE #scope_review_out (category_code NVARCHAR(40) NULL, record_id BIGINT NULL,
                                    record_code NVARCHAR(120) NULL, record_name NVARCHAR(400) NULL,
                                    status NVARCHAR(60) NULL, reason NVARCHAR(MAX) NULL);
    EXEC grac_practice.sp_org_assurance_scope_discover
         @organization_id = @organization_id,
         @definition_id   = @def,
         @version_id      = @ver,
         @execution_id    = @execution_id;
    INSERT #scope_review_cat (category_code, category_name, display_order, item_count, is_included)
    VALUES (N'MANUAL', N'Manual Items', 99, 0, 1);

    DECLARE @rc TABLE (category_code NVARCHAR(40) PRIMARY KEY, is_included BIT NOT NULL);
    DECLARE @rx TABLE (category_code NVARCHAR(40) NULL, record_id BIGINT NULL, reason NVARCHAR(1000) NULL);
    DECLARE @rm TABLE (category_code NVARCHAR(40) NULL, item_name NVARCHAR(400) NULL, note NVARCHAR(1000) NULL);
    IF @review_json IS NOT NULL
    BEGIN
        IF ISJSON(@review_json) <> 1
            THROW 54037, 'The scope review is not valid. Reload the scope and try again.', 1;
        INSERT @rc (category_code, is_included)
        SELECT UPPER(LTRIM(RTRIM(x.code))), MAX(CAST(ISNULL(x.isIncluded, 1) AS INT))
          FROM OPENJSON(@review_json, '$.categories')
               WITH (code NVARCHAR(40) '$.code', isIncluded BIT '$.isIncluded') x
         WHERE x.code IS NOT NULL
         GROUP BY UPPER(LTRIM(RTRIM(x.code)));
        INSERT @rx (category_code, record_id, reason)
        SELECT UPPER(LTRIM(RTRIM(x.categoryCode))), x.recordId,
               LEFT(NULLIF(LTRIM(RTRIM(x.reason)), N''), 1000)
          FROM OPENJSON(@review_json, '$.excluded')
               WITH (categoryCode NVARCHAR(40) '$.categoryCode', recordId BIGINT '$.recordId',
                     reason NVARCHAR(MAX) '$.reason') x;
        INSERT @rm (category_code, item_name, note)
        SELECT UPPER(LTRIM(RTRIM(ISNULL(x.categoryCode, N'MANUAL')))),
               LEFT(NULLIF(LTRIM(RTRIM(x.name)), N''), 400),
               LEFT(NULLIF(LTRIM(RTRIM(x.note)), N''), 1000)
          FROM OPENJSON(@review_json, '$.manual')
               WITH (categoryCode NVARCHAR(40) '$.categoryCode', name NVARCHAR(MAX) '$.name',
                     note NVARCHAR(MAX) '$.note') x;
    END

    IF EXISTS (SELECT 1 FROM (SELECT category_code FROM @rc UNION ALL SELECT category_code FROM @rx
                              UNION ALL SELECT category_code FROM @rm) u
                WHERE NOT EXISTS (SELECT 1 FROM #scope_review_cat c WHERE c.category_code = u.category_code))
        THROW 54039, 'Unknown scope category in the review.', 1;
    IF EXISTS (SELECT 1 FROM @rx WHERE category_code = N'PRACTICE_INSTANCE')
        THROW 54037, 'Exclude a practice instance in the scope list above, not in the related records.', 1;
    IF EXISTS (SELECT 1 FROM @rx WHERE record_id IS NULL OR reason IS NULL)
        THROW 54037, 'Every related record you untick needs a reason.', 1;
    IF EXISTS (SELECT 1 FROM @rx x
                WHERE NOT EXISTS (SELECT 1 FROM #scope_review_out o
                                   WHERE o.category_code = x.category_code AND o.record_id = x.record_id))
        THROW 54037, 'An unticked record is no longer related to the scope. Reload the scope and try again.', 1;
    IF EXISTS (SELECT 1 FROM @rm WHERE item_name IS NULL)
        THROW 54038, 'Every manual item needs a name.', 1;

    DECLARE @review_id BIGINT, @review_version INT;
    SET @review_version = ISNULL((SELECT MAX(version_no) FROM grac_practice.org_assurance_execution_scope_review
                                   WHERE org_assurance_execution_id = @execution_id), 0) + 1;
    INSERT INTO grac_practice.org_assurance_execution_scope_review
        (organization_id, org_assurance_execution_id, org_assurance_definition_version_id,
         version_no, review_status, approved_by, approved_employee_id, approved_dt, entered_by)
    VALUES (@organization_id, @execution_id, @ver,
            @review_version, N'Approved', @actor, @employee_id, SYSUTCDATETIME(), @actor);
    SET @review_id = SCOPE_IDENTITY();

    -- Practice Instances are the scope itself: always included.
    INSERT INTO grac_practice.org_assurance_execution_scope_review_category
        (org_assurance_execution_scope_review_id, organization_id, category_code, category_name,
         display_order, item_count, is_included)
    SELECT @review_id, @organization_id, c.category_code, c.category_name, c.display_order,
           CASE WHEN c.category_code = N'MANUAL' THEN 0 ELSE ISNULL(c.item_count, 0) END
             + (SELECT COUNT(*) FROM @rm m WHERE m.category_code = c.category_code),
           CASE WHEN c.category_code = N'PRACTICE_INSTANCE' THEN 1
                ELSE ISNULL(rc.is_included, ISNULL(c.is_included, 1)) END
      FROM #scope_review_cat c
      LEFT JOIN @rc rc ON rc.category_code = c.category_code;

    INSERT INTO grac_practice.org_assurance_execution_scope_review_item
        (org_assurance_execution_scope_review_id, organization_id, category_code,
         record_id, record_code, record_name, record_status, related_reason,
         is_kept, exclusion_reason, is_manual, manual_note)
    SELECT @review_id, @organization_id, o.category_code,
           o.record_id, o.record_code, LEFT(o.record_name, 400), o.status, o.reason,
           CASE WHEN x.record_id IS NULL THEN 1 ELSE 0 END, x.reason, 0, NULL
      FROM #scope_review_out o
      OUTER APPLY (SELECT TOP 1 rx.record_id, rx.reason FROM @rx rx
                    WHERE rx.category_code = o.category_code AND rx.record_id = o.record_id) x
    UNION ALL
    SELECT @review_id, @organization_id, m.category_code,
           NULL, NULL, m.item_name, NULL, N'Added by the auditor',
           1, NULL, 1, m.note
      FROM @rm m;

    -- Freezing starts the audit.
    EXEC grac_practice.sp_org_assurance_execution_transition
         @organization_id     = @organization_id,
         @execution_id        = @execution_id,
         @expected_from_codes = N'Planned',
         @to_code             = N'InProgress',
         @stamp_start         = 1,
         @stamp_end           = 0,
         @actor               = @actor;

    COMMIT;

    SELECT e.org_assurance_execution_id AS ExecutionId,
           e.execution_code             AS ExecutionCode,
           e.total_entity_count         AS TotalEntityCount,
           (SELECT COUNT(*) FROM @excl)  AS ExcludedCount,
           @review_id                    AS ReviewId,          -- 563
           @review_version               AS ReviewVersionNo    -- 563
      FROM grac_practice.org_assurance_execution e
     WHERE e.org_assurance_execution_id = @execution_id;
END
GO

-- =====================================================================
-- 5. sp_org_assurance_execution_scope_review_get -- Step 3 in My Audits.
--    One shape, three result sets:
--      1 header     ReviewId (NULL = not reviewed yet), VersionNo,
--                   ReviewStatus, ApprovedBy, ApprovedDt, IsFrozen
--      2 categories CategoryCode, CategoryName, DisplayOrder, ItemCount,
--                   IsIncluded
--      3 items      CategoryCode, RecordId, RecordCode, RecordName, Status,
--                   Reason, IsKept, ExclusionReason, IsManual, ManualNote
--    Frozen with a snapshot: the snapshot (latest version). Frozen before
--    563: the header only. Live: the discovery over the scope now, every
--    record kept, the definition's category ticks.
-- =====================================================================
CREATE OR ALTER PROCEDURE grac_practice.sp_org_assurance_execution_scope_review_get
    @organization_id BIGINT,
    @execution_id    BIGINT
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;
    IF @organization_id IS NULL OR @execution_id IS NULL
        THROW 54009, 'organization_id and execution_id are required.', 1;

    DECLARE @def BIGINT, @ver BIGINT, @frozen DATETIME2;
    SELECT @def    = e.org_assurance_definition_id,
           @ver    = e.org_assurance_definition_version_id,
           @frozen = e.scope_frozen_at
      FROM grac_practice.org_assurance_execution e
     WHERE e.org_assurance_execution_id = @execution_id
       AND e.organization_id = @organization_id
       AND e.is_active = 1;
    IF @def IS NULL
        THROW 54010, 'Execution not found or not accessible in this organization.', 1;

    DECLARE @review_id BIGINT = (SELECT TOP 1 r.org_assurance_execution_scope_review_id
                                   FROM grac_practice.org_assurance_execution_scope_review r
                                  WHERE r.org_assurance_execution_id = @execution_id
                                    AND r.organization_id = @organization_id
                                  ORDER BY r.version_no DESC);

    IF @review_id IS NOT NULL
    BEGIN
        SELECT r.org_assurance_execution_scope_review_id AS ReviewId,
               r.version_no    AS VersionNo,
               r.review_status AS ReviewStatus,
               r.approved_by   AS ApprovedBy,
               r.approved_dt   AS ApprovedDt,
               CAST(1 AS BIT)  AS IsFrozen
          FROM grac_practice.org_assurance_execution_scope_review r
         WHERE r.org_assurance_execution_scope_review_id = @review_id;

        SELECT c.category_code AS CategoryCode, c.category_name AS CategoryName,
               c.display_order AS DisplayOrder, c.item_count AS ItemCount,
               c.is_included   AS IsIncluded
          FROM grac_practice.org_assurance_execution_scope_review_category c
         WHERE c.org_assurance_execution_scope_review_id = @review_id
         ORDER BY c.display_order;

        SELECT i.category_code AS CategoryCode, i.record_id AS RecordId,
               i.record_code   AS RecordCode,   i.record_name AS RecordName,
               i.record_status AS Status,       i.related_reason AS Reason,
               i.is_kept       AS IsKept,       i.exclusion_reason AS ExclusionReason,
               i.is_manual     AS IsManual,     i.manual_note AS ManualNote
          FROM grac_practice.org_assurance_execution_scope_review_item i
         WHERE i.org_assurance_execution_scope_review_id = @review_id
         ORDER BY i.category_code, i.is_manual, i.record_code, i.record_name;
        RETURN;
    END

    CREATE TABLE #scope_review_cat (category_code NVARCHAR(40) NULL, category_name NVARCHAR(80) NULL,
                                    display_order INT NULL, item_count BIGINT NULL, is_included BIT NULL);
    CREATE TABLE #scope_review_out (category_code NVARCHAR(40) NULL, record_id BIGINT NULL,
                                    record_code NVARCHAR(120) NULL, record_name NVARCHAR(400) NULL,
                                    status NVARCHAR(60) NULL, reason NVARCHAR(MAX) NULL);
    IF @frozen IS NULL
    BEGIN
        EXEC grac_practice.sp_org_assurance_scope_discover
             @organization_id = @organization_id,
             @definition_id   = @def,
             @version_id      = @ver,
             @execution_id    = @execution_id;
        INSERT #scope_review_cat (category_code, category_name, display_order, item_count, is_included)
        VALUES (N'MANUAL', N'Manual Items', 99, 0, 1);
    END

    SELECT CAST(NULL AS BIGINT)        AS ReviewId,
           CAST(NULL AS INT)           AS VersionNo,
           CAST(NULL AS NVARCHAR(30))  AS ReviewStatus,
           CAST(NULL AS NVARCHAR(100)) AS ApprovedBy,
           CAST(NULL AS DATETIME2)     AS ApprovedDt,
           CAST(CASE WHEN @frozen IS NULL THEN 0 ELSE 1 END AS BIT) AS IsFrozen;

    SELECT c.category_code AS CategoryCode, c.category_name AS CategoryName,
           c.display_order AS DisplayOrder, ISNULL(c.item_count, 0) AS ItemCount,
           CAST(CASE WHEN c.category_code = N'PRACTICE_INSTANCE' THEN 1
                     ELSE ISNULL(c.is_included, 1) END AS BIT) AS IsIncluded
      FROM #scope_review_cat c
     ORDER BY c.display_order;

    SELECT o.category_code AS CategoryCode, o.record_id AS RecordId,
           o.record_code   AS RecordCode,   o.record_name AS RecordName,
           o.status        AS Status,       o.reason AS Reason,
           CAST(1 AS BIT)  AS IsKept,       CAST(NULL AS NVARCHAR(1000)) AS ExclusionReason,
           CAST(0 AS BIT)  AS IsManual,     CAST(NULL AS NVARCHAR(1000)) AS ManualNote
      FROM #scope_review_out o
     ORDER BY o.category_code, o.record_code, o.record_name;
END
