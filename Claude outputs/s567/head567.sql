-- 8c. An execution's questions from its snapshot (internal; idempotent).
CREATE OR ALTER PROCEDURE grac_practice.sp_org_assurance_wp_question_sync
    @execution_id BIGINT,
    @actor        NVARCHAR(100) = 'system'
AS
BEGIN
    SET NOCOUNT ON;
    DECLARE @org BIGINT, @qjson NVARCHAR(MAX);
    SELECT @org = organization_id, @qjson = questions_snapshot_json
      FROM grac_practice.org_assurance_execution
     WHERE org_assurance_execution_id = @execution_id;
    IF @org IS NULL OR ISJSON(@qjson) <> 1 RETURN;

    INSERT INTO grac_practice.org_assurance_execution_question
        (organization_id, org_assurance_execution_id, question_id, question_code, question_text,
         question_set_code, question_set_name, set_order, display_order, testing_guidance, weight,
         is_mandatory, evidence_type_name, expected_evidence, entered_by)
    SELECT @org, @execution_id, j.QuestionId, j.QuestionCode, j.QuestionText,
           j.QuestionSetCode, j.QuestionSetName, j.SetOrder, j.DisplayOrder, j.HelpText, j.Weight,
           j.IsMandatory, j.EvidenceTypeName, j.ExpectedEvidence, @actor
      FROM (SELECT x.*, ROW_NUMBER() OVER (PARTITION BY x.QuestionId ORDER BY x.SetOrder, x.DisplayOrder) AS rn
              FROM OPENJSON(@qjson) WITH (
                    SetOrder         INT            '$.SetOrder',
                    QuestionSetCode  NVARCHAR(120)  '$.QuestionSetCode',
                    QuestionSetName  NVARCHAR(300)  '$.QuestionSetName',
                    QuestionId       BIGINT         '$.QuestionId',
                    QuestionCode     NVARCHAR(120)  '$.QuestionCode',
                    QuestionText     NVARCHAR(MAX)  '$.QuestionText',
                    HelpText         NVARCHAR(MAX)  '$.HelpText',
                    Weight           DECIMAL(10,2)  '$.Weight',
                    IsMandatory      BIT            '$.IsMandatory',
                    DisplayOrder     INT            '$.DisplayOrder',
                    EvidenceTypeName NVARCHAR(160)  '$.EvidenceTypeName',
                    ExpectedEvidence NVARCHAR(MAX)  '$.ExpectedEvidence') x
             WHERE x.QuestionId IS NOT NULL) j
     WHERE j.rn = 1
       AND NOT EXISTS (SELECT 1 FROM grac_practice.org_assurance_execution_question q
                        WHERE q.org_assurance_execution_id = @execution_id AND q.question_id = j.QuestionId);
END
GO

-- 8d. The execution score (internal): question weight x conclusion
-- (Satisfactory 1, Partial 0.5, Unsatisfactory 0; Not Applicable and
-- open questions left out), as a percentage, in the audit version's band.
CREATE OR ALTER PROCEDURE grac_practice.sp_org_assurance_execution_score_refresh
    @execution_id BIGINT
AS
BEGIN
    SET NOCOUNT ON;
    DECLARE @w DECIMAL(18,4), @s DECIMAL(18,4), @score DECIMAL(6,2) = NULL,
            @ver BIGINT, @band_code NVARCHAR(60) = NULL, @band_name NVARCHAR(160) = NULL;
    SELECT @w = SUM(CASE WHEN ISNULL(q.weight, 0) > 0 THEN q.weight ELSE 1 END),
           @s = SUM(CASE WHEN ISNULL(q.weight, 0) > 0 THEN q.weight ELSE 1 END
                    * CASE q.conclusion_code WHEN N'SATISFACTORY' THEN 1.0 WHEN N'PARTIAL' THEN 0.5 ELSE 0.0 END)
      FROM grac_practice.org_assurance_execution_question q
     WHERE q.org_assurance_execution_id = @execution_id
       AND q.conclusion_code IN (N'SATISFACTORY', N'PARTIAL', N'UNSATISFACTORY');
    IF ISNULL(@w, 0) > 0 SET @score = ROUND(100.0 * @s / @w, 2);

    SELECT @ver = org_assurance_definition_version_id
      FROM grac_practice.org_assurance_execution WHERE org_assurance_execution_id = @execution_id;
    IF @score IS NOT NULL
        SELECT TOP 1 @band_code = b.band_code, @band_name = b.band_name
          FROM grac_practice.org_assurance_scoring_band b
         WHERE b.org_assurance_definition_version_id = @ver
           AND b.is_active = 1
           AND @score BETWEEN b.min_score AND b.max_score
         ORDER BY b.band_order;

    UPDATE grac_practice.org_assurance_execution
       SET score_pct = @score, score_band_code = @band_code, score_band_name = @band_name,
           score_refreshed_dt = SYSUTCDATETIME()
     WHERE org_assurance_execution_id = @execution_id;
END
