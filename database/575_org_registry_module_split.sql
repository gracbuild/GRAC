-- =====================================================================
-- 575_org_registry_module_split.sql
--
-- Organization Registry -- module split (2026-11-16, sir):
--
--   Organization Management (GRAC's own administration module) keeps ONLY
--   Organizations and Legal Entities:
--       'org-registry'            "Organizations & Legal Entities"
--                                 (unchanged placement: under the inactive
--                                 'Organization' group, hidden from the
--                                 Practice Management sidebar -- 570 / 512)
--
--   Everything else moves to Practice Management -> Organization, where the
--   organization's own administrator maintains it. Organizations and Legal
--   Entities are shown there read-only (the Web proxy and the procedures
--   refuse saves -- error 52707):
--       'org-registry-structure'  "Organization Structure" (NEW)
--                                 Organizations (read-only), Legal Entities
--                                 (read-only), Units, Locations, Departments
--       'org-registry-people'     "People & Governance"
--       'org-registry-operations' "Business Operations"
--   The three sit under the Practice Management root
--   'organization-administration' ("Organization"), shown in the sidebar.
--   'organization-administration' keeps its own url, so it becomes a
--   page-parent (276 / _PracticeMenuTree data-nav-href): clicking it still
--   opens the Organization Administration page.
--
--   Grants: each role gets on the three menus the VIEW / ADD / EDIT it has
--   on 'organization-administration' (only rows not there yet; nothing
--   existing changes). A role's org-registry grant is no longer what opens
--   them (PracticeController.ScreenPermissionArea, 575).
--
-- Needs procedures regenerated by 571 (re-run 571 BEFORE this script: the
-- list / save procedures gained @allowed_legal_entity_ids).
-- Requires 570, 574. Idempotent. ASCII only. 274 amended to match.
-- Rollback: 575_org_registry_module_split_rollback.sql
-- =====================================================================
SET NOCOUNT ON;
SET XACT_ABORT ON;
SET NOEXEC OFF;
GO
IF NOT EXISTS (SELECT 1 FROM grac_practice.menu_master WHERE menu_key = N'org-registry')
   OR NOT EXISTS (SELECT 1 FROM grac_practice.menu_master WHERE menu_key = N'org-registry-people')
   OR NOT EXISTS (SELECT 1 FROM grac_practice.menu_master WHERE menu_key = N'organization-administration')
   OR COL_LENGTH('grac_practice.menu_master','show_in_sidebar') IS NULL
BEGIN
    PRINT 'ABORT (575): run 570 and 574 first. Nothing was changed.';
    SET NOEXEC ON;
END
GO
IF NOT EXISTS (SELECT 1 FROM sys.parameters
                WHERE object_id = OBJECT_ID('grac_practice.sp_orgreg_units_save')
                  AND name = N'@allowed_legal_entity_ids')
BEGIN
    PRINT 'ABORT (575): re-run 571 first (procedures without @allowed_legal_entity_ids). Nothing was changed.';
    SET NOEXEC ON;
END
GO

BEGIN TRAN;

-- ---------------------------------------------------------------------
-- 1. Menu rows.
-- ---------------------------------------------------------------------
MERGE grac_practice.menu_master AS t
USING (VALUES
    (N'org-registry',            N'Organizations & Legal Entities', N'Practice/Index/org-registry',             1, N'sitemap',         N'Organization'),
    (N'org-registry-structure',  N'Organization Structure',         N'Practice/Index/org-registry-structure',  10, N'sitemap',         N'Organization'),
    (N'org-registry-people',     N'People & Governance',            N'Practice/Index/org-registry-people',     20, N'users',           N'Organization'),
    (N'org-registry-operations', N'Business Operations',            N'Practice/Index/org-registry-operations', 30, N'diagram-project', N'Organization')
) AS s(menu_key, menu_name, menu_url, display_order, icon_class, module_type)
ON t.menu_key = s.menu_key
WHEN MATCHED AND (ISNULL(t.menu_name, N'') <> s.menu_name OR ISNULL(t.menu_url, N'') <> s.menu_url
               OR t.display_order <> s.display_order OR ISNULL(t.icon_class, N'') <> s.icon_class
               OR ISNULL(t.module_type, N'') <> s.module_type OR t.status <> N'Active') THEN UPDATE SET
    menu_name = s.menu_name, menu_url = s.menu_url, display_order = s.display_order, icon_class = s.icon_class,
    module_type = s.module_type, status = N'Active', updated_by = N'seed-575', updated_dt = SYSUTCDATETIME()
WHEN NOT MATCHED BY TARGET THEN
    INSERT (menu_key, menu_name, menu_url, display_order, icon_class, module_type, status, entered_by)
    VALUES (s.menu_key, s.menu_name, s.menu_url, s.display_order, s.icon_class, s.module_type, N'Active', N'seed-575');
PRINT CONCAT('575: registry menu rows upserted: ', @@ROWCOUNT);

-- 2. Placement: the three Practice Management screens under the
--    'organization-administration' root, visible in the sidebar.
UPDATE c SET parent_menu_id = p.menu_id, updated_by = N'seed-575', updated_dt = SYSUTCDATETIME()
  FROM grac_practice.menu_master c
  JOIN grac_practice.menu_master p ON p.menu_key = N'organization-administration'
 WHERE c.menu_key IN (N'org-registry-structure', N'org-registry-people', N'org-registry-operations')
   AND ISNULL(c.parent_menu_id, -1) <> p.menu_id;
PRINT CONCAT('575: menus placed under Organization: ', @@ROWCOUNT);
COMMIT;
GO
-- Dynamic SQL: show_in_sidebar is checked above, but a static reference
-- would still fail to compile on a database without it (390).
EXEC sp_executesql N'
    UPDATE grac_practice.menu_master SET show_in_sidebar = 1, updated_by = N''seed-575'', updated_dt = SYSUTCDATETIME()
     WHERE menu_key IN (N''org-registry-structure'', N''org-registry-people'', N''org-registry-operations'')
       AND show_in_sidebar = 0;
    -- org-registry stays Organization Management only (2d guard, 512 / 570).
    UPDATE grac_practice.menu_master SET show_in_sidebar = 0, updated_by = N''seed-575'', updated_dt = SYSUTCDATETIME()
     WHERE menu_key = N''org-registry'' AND show_in_sidebar = 1;';
GO

-- ---------------------------------------------------------------------
-- 3. Grants: copy each role's 'organization-administration' VIEW / ADD /
--    EDIT onto the three menus (missing rows only).
-- ---------------------------------------------------------------------
IF OBJECT_ID('grac_practice.organization_role_menu_permission','U') IS NOT NULL
    EXEC sp_executesql N'
        INSERT grac_practice.organization_role_menu_permission
            (role_id, menu_id, can_view, can_add, can_edit, can_delete, can_approve,
             status, record_status_id, entered_by, entered_dt)
        SELECT g.role_id, m.menu_id, g.can_view, g.can_add, g.can_edit, 0, 0, N''Active'',
               (SELECT TOP (1) record_status_id FROM grac_practice.record_status_master WHERE status_code = N''Active''),
               N''seed-575'', SYSUTCDATETIME()
          FROM grac_practice.organization_role_menu_permission g
          JOIN grac_practice.menu_master a ON a.menu_id = g.menu_id AND a.menu_key = N''organization-administration''
          JOIN grac_practice.menu_master m ON m.menu_key IN (N''org-registry-structure'', N''org-registry-people'', N''org-registry-operations'')
         WHERE g.status = N''Active''
           AND NOT EXISTS (SELECT 1 FROM grac_practice.organization_role_menu_permission e
                            WHERE e.role_id = g.role_id AND e.menu_id = m.menu_id);
        PRINT CONCAT(''575: grants copied from organization-administration: '', @@ROWCOUNT);';
GO

SET NOEXEC OFF;
GO
PRINT '--- 575 verification ---';
SELECT m.menu_key, m.menu_name, m.status, m.display_order,
       (SELECT p.menu_key FROM grac_practice.menu_master p WHERE p.menu_id = m.parent_menu_id) AS parent_key,
       (SELECT COUNT(*) FROM grac_practice.organization_role_menu_permission g
         WHERE g.menu_id = m.menu_id AND g.can_view = 1) AS roles_with_view
  FROM grac_practice.menu_master m
 WHERE m.menu_key IN (N'org-registry', N'org-registry-structure', N'org-registry-people', N'org-registry-operations')
 ORDER BY m.display_order;
GO
PRINT '575 complete. Sign out and in again -- the menu and grants are read at sign-in.';
GO
