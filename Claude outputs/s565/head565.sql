    @organization_id BIGINT,
    @plan_id         BIGINT,
    @programme_id    BIGINT,
    @actor           NVARCHAR(100) = 'system'
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;
    IF @organization_id IS NULL OR @plan_id IS NULL OR @programme_id IS NULL
        THROW 53902, 'organization_id, plan_id and programme_id are required.', 1;

    DECLARE @plan_status NVARCHAR(60);
    SELECT @plan_status = s.status_code
      FROM grac_practice.org_assurance_plan p
      JOIN grac_practice.org_assurance_plan_status_master s
           ON s.org_assurance_plan_status_id = p.status_id
     WHERE p.org_assurance_plan_id = @plan_id AND p.organization_id = @organization_id AND p.is_active = 1;
    IF @plan_status IS NULL THROW 53907, 'Plan not found.', 1;
    IF @plan_status NOT IN (N'Draft', N'Submitted')
        THROW 53909, 'Programmes can be changed only while the plan is Draft or Submitted.', 1;
    IF NOT EXISTS (SELECT 1 FROM grac_practice.org_assurance_plan_programme
                    WHERE org_assurance_programme_id = @programme_id
                      AND org_assurance_plan_id = @plan_id AND is_active = 1)
        THROW 53944, 'The programme is not part of this plan.', 1;
    IF EXISTS (SELECT 1 FROM grac_practice.org_assurance_plan_item
                WHERE org_assurance_programme_id = @programme_id AND is_active = 1)
        THROW 53946, 'The programme still has engagements. Move or remove them first.', 1;

    UPDATE grac_practice.org_assurance_plan_programme
       SET is_active = 0, updated_by = @actor, updated_dt = SYSUTCDATETIME()
     WHERE org_assurance_programme_id = @programme_id;
END
GO

-- =====================================================================
-- 7e. Revise an Approved / Active plan: reason, version + 1, the old
--     values in the revision history, back to Draft (re-approval).
-- =====================================================================
CREATE OR ALTER PROCEDURE grac_practice.sp_org_assurance_plan_revise
    @organization_id BIGINT,
    @plan_id         BIGINT,
    @reason          NVARCHAR(2000),
    @actor           NVARCHAR(100) = 'system'
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;
    IF @organization_id IS NULL OR @plan_id IS NULL
        THROW 53902, 'organization_id and plan_id are required.', 1;
    IF NULLIF(LTRIM(RTRIM(@reason)), N'') IS NULL
        THROW 53949, 'Give the reason for revising the plan.', 1;

    DECLARE @status NVARCHAR(60), @version INT, @org BIGINT;
    SELECT @status = s.status_code, @version = p.version, @org = p.organization_id
      FROM grac_practice.org_assurance_plan p
      JOIN grac_practice.org_assurance_plan_status_master s
           ON s.org_assurance_plan_status_id = p.status_id
     WHERE p.org_assurance_plan_id = @plan_id AND p.is_active = 1;
    IF @org IS NULL THROW 53907, 'Plan not found.', 1;
    IF @org <> @organization_id THROW 53908, 'Plan belongs to a different organization.', 1;
    IF @status NOT IN (N'Approved', N'Active')
        THROW 53949, 'Only an Approved or Active plan is revised; a Draft or Submitted plan is edited directly.', 1;

    DECLARE @snapshot NVARCHAR(MAX) = (
        SELECT p.plan_code AS planCode, p.plan_name AS planName, p.plan_type AS planType,
               p.financial_year AS financialYear, p.period_from AS periodFrom, p.period_to AS periodTo,
               p.owner_display_name AS owner, p.objectives, p.planned_coverage AS plannedCoverage,
               p.planned_budget AS plannedBudget, p.budget_currency AS budgetCurrency,
               p.planned_effort_days AS plannedEffortDays, p.resources_note AS resources,
               p.description, p.version, @status AS status,
               (SELECT g.programme_code AS code, g.programme_name AS name, g.methodology_name AS methodology,
                       g.owner_display_name AS owner, g.objective,
                       (SELECT COUNT(*) FROM grac_practice.org_assurance_plan_item i
                         WHERE i.org_assurance_programme_id = g.org_assurance_programme_id AND i.is_active = 1) AS engagements
                  FROM grac_practice.org_assurance_plan_programme g
                 WHERE g.org_assurance_plan_id = p.org_assurance_plan_id AND g.is_active = 1
                 ORDER BY g.display_order
                   FOR JSON PATH) AS programmes
          FROM grac_practice.org_assurance_plan p
         WHERE p.org_assurance_plan_id = @plan_id
           FOR JSON PATH, WITHOUT_ARRAY_WRAPPER);

    BEGIN TRAN;
    INSERT INTO grac_practice.org_assurance_plan_revision
        (org_assurance_plan_id, organization_id, from_version, to_version, from_status_code,
         reason, snapshot_json, revised_by, revised_dt)
    VALUES (@plan_id, @organization_id, @version, @version + 1, @status,
            LEFT(LTRIM(RTRIM(@reason)), 2000), @snapshot, @actor, SYSUTCDATETIME());

    EXEC grac_practice.sp_org_assurance_plan_transition
         @organization_id    = @organization_id,
         @plan_id            = @plan_id,
         @expected_from_code = @status,
         @to_code            = N'Draft',
         @actor              = @actor;

    UPDATE grac_practice.org_assurance_plan
       SET version = @version + 1, updated_by = @actor, updated_dt = SYSUTCDATETIME()
     WHERE org_assurance_plan_id = @plan_id;
    COMMIT;

    SELECT @plan_id AS PlanId, @version + 1 AS Version;
END
GO

-- =====================================================================
-- 7f. A plan's revision history (newest first)
-- =====================================================================
CREATE OR ALTER PROCEDURE grac_practice.sp_org_assurance_plan_revision_list
    @organization_id BIGINT,
    @plan_id         BIGINT
AS
BEGIN
    SET NOCOUNT ON;
    IF @organization_id IS NULL OR @plan_id IS NULL
        THROW 53902, 'organization_id and plan_id are required.', 1;
    SELECT r.org_assurance_plan_revision_id AS RevisionId,
           r.from_version     AS FromVersion,
           r.to_version       AS ToVersion,
           r.from_status_code AS FromStatusCode,
           r.reason           AS Reason,
           r.snapshot_json    AS SnapshotJson,
           r.revised_by       AS RevisedBy,
           r.revised_dt       AS RevisedDt
      FROM grac_practice.org_assurance_plan_revision r
     WHERE r.org_assurance_plan_id = @plan_id
       AND r.organization_id = @organization_id
     ORDER BY r.to_version DESC, r.org_assurance_plan_revision_id DESC;
END
GO

