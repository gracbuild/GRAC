-- =====================================================================
-- 7. Who someone is on an execution; a question's papers
-- =====================================================================
-- The lead is the execution's auditor (the engagement's lead, 566). The
-- team is the engagement's active LEAD / MEMBER / SME with an employee.
-- The reviewer is the engagement's active REVIEWER, else the lead.
CREATE OR ALTER FUNCTION grac_practice.fn_org_assurance_wp_roles(@execution_id BIGINT, @employee_id BIGINT)
RETURNS TABLE
AS
RETURN
    SELECT e.owner_employee_id                              AS lead_employee_id,
           e.owner_display_name                             AS lead_name,
           COALESCE(rv.employee_id, e.owner_employee_id)    AS reviewer_employee_id,
           COALESCE(rv.member_name, e.owner_display_name)   AS reviewer_name,
           CAST(CASE WHEN @employee_id IS NOT NULL AND e.owner_employee_id = @employee_id THEN 1 ELSE 0 END AS BIT) AS is_lead,
           CAST(CASE WHEN @employee_id IS NOT NULL
                      AND (e.owner_employee_id = @employee_id
                           OR EXISTS (SELECT 1 FROM grac_practice.org_assurance_engagement_team t
                                       WHERE t.org_assurance_plan_item_id = e.org_assurance_plan_item_id
                                         AND t.is_active = 1
                                         AND t.team_role IN (N'LEAD', N'MEMBER', N'SME')
                                         AND t.employee_id = @employee_id))
                     THEN 1 ELSE 0 END AS BIT)             AS is_team,
           CAST(CASE WHEN @employee_id IS NOT NULL AND COALESCE(rv.employee_id, e.owner_employee_id) = @employee_id
                     THEN 1 ELSE 0 END AS BIT)             AS is_reviewer
      FROM grac_practice.org_assurance_execution e
     OUTER APPLY (SELECT TOP 1 t.employee_id, t.member_name
                    FROM grac_practice.org_assurance_engagement_team t
                   WHERE t.org_assurance_plan_item_id = e.org_assurance_plan_item_id
                     AND t.is_active = 1 AND t.team_role = N'REVIEWER' AND t.employee_id IS NOT NULL
                   ORDER BY t.engagement_team_id) rv
     WHERE e.org_assurance_execution_id = @execution_id;
GO

-- A question's papers by state, and the suggested conclusion: the worst
-- result among its APPROVED papers (Not Applicable only when every
-- approved paper is).
CREATE OR ALTER FUNCTION grac_practice.fn_org_assurance_wp_question_state(@execution_question_id BIGINT)
RETURNS TABLE
AS
RETURN
    SELECT COUNT(*)                                                                   AS paper_count,
           ISNULL(SUM(CASE WHEN p.review_status = N'Approved' THEN 1 ELSE 0 END), 0)               AS approved_count,
           ISNULL(SUM(CASE WHEN p.review_status IN (N'Pending', N'Reviewed') THEN 1 ELSE 0 END), 0) AS in_review_count,
           ISNULL(SUM(CASE WHEN p.review_status IN (N'Draft', N'Returned') THEN 1 ELSE 0 END), 0)  AS open_count,
           CASE MAX(CASE WHEN p.review_status = N'Approved'
                         THEN CASE p.test_result WHEN N'UNSATISFACTORY' THEN 3 WHEN N'PARTIAL' THEN 2
                                                 WHEN N'SATISFACTORY' THEN 1 WHEN N'NA' THEN 0 END END)
                WHEN 3 THEN N'UNSATISFACTORY' WHEN 2 THEN N'PARTIAL' WHEN 1 THEN N'SATISFACTORY' WHEN 0 THEN N'NA'
           END                                                                        AS suggested_conclusion
      FROM grac_practice.org_assurance_working_paper p
     WHERE p.execution_question_id = @execution_question_id
       AND p.is_active = 1;
GO

