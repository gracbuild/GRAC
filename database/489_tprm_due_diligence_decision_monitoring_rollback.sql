-- Tables: dropped only when they hold no rows; otherwise
-- they are kept (the procedures are gone, the data is not) and the
-- script says so. Delete the rows deliberately first to drop them.
IF OBJECT_ID('grac_practice.tprm_dd_assessment','U') IS NOT NULL
BEGIN
    IF NOT EXISTS (SELECT 1 FROM grac_practice.tprm_dd_assessment)
       AND NOT EXISTS (SELECT 1 FROM grac_practice.tprm_dd_questionnaire)
       AND NOT EXISTS (SELECT 1 FROM grac_practice.tprm_dd_response)
       AND NOT EXISTS (SELECT 1 FROM grac_practice.tprm_safeguard_assessment)
       AND NOT EXISTS (SELECT 1 FROM grac_practice.tprm_evidence_link)
       AND NOT EXISTS (SELECT 1 FROM grac_practice.tprm_finding)
       AND NOT EXISTS (SELECT 1 FROM grac_practice.tprm_decision)
       AND NOT EXISTS (SELECT 1 FROM grac_practice.tprm_decision_approval)
       AND NOT EXISTS (SELECT 1 FROM grac_practice.tprm_onboarding_item)
       AND NOT EXISTS (SELECT 1 FROM grac_practice.tprm_engagement_deviation)
       AND NOT EXISTS (SELECT 1 FROM grac_practice.tprm_review)
    BEGIN
        DECLARE @fk NVARCHAR(MAX) = N'';
        SELECT @fk = @fk + N'ALTER TABLE grac_practice.' + QUOTENAME(OBJECT_NAME(fk.parent_object_id))
                         + N' DROP CONSTRAINT ' + QUOTENAME(fk.name) + N';'
        FROM sys.foreign_keys fk
        WHERE OBJECT_SCHEMA_NAME(fk.parent_object_id) = N'grac_practice'
          AND OBJECT_NAME(fk.parent_object_id) IN (N'tprm_dd_assessment', N'tprm_dd_questionnaire', N'tprm_dd_response', N'tprm_safeguard_assessment', N'tprm_evidence_link', N'tprm_finding', N'tprm_decision', N'tprm_decision_approval', N'tprm_onboarding_item', N'tprm_engagement_deviation', N'tprm_review');
        EXEC sp_executesql @fk;
        DROP TABLE IF EXISTS grac_practice.tprm_review;
        DROP TABLE IF EXISTS grac_practice.tprm_engagement_deviation;
        DROP TABLE IF EXISTS grac_practice.tprm_onboarding_item;
        DROP TABLE IF EXISTS grac_practice.tprm_decision_approval;
        DROP TABLE IF EXISTS grac_practice.tprm_decision;
        DROP TABLE IF EXISTS grac_practice.tprm_finding;
        DROP TABLE IF EXISTS grac_practice.tprm_evidence_link;
        DROP TABLE IF EXISTS grac_practice.tprm_safeguard_assessment;
        DROP TABLE IF EXISTS grac_practice.tprm_dd_response;
        DROP TABLE IF EXISTS grac_practice.tprm_dd_questionnaire;
        DROP TABLE IF EXISTS grac_practice.tprm_dd_assessment;
        PRINT '489 rollback: tables dropped.';
    END
    ELSE
        PRINT '489 rollback: due-diligence / decision / review data exists -- tables kept.';
END
GO

-- Risk Centre source: removed only when no candidate uses it.
IF OBJECT_ID('grac_practice.risk_source_master','U') IS NOT NULL
BEGIN
    IF NOT EXISTS (SELECT 1 FROM grac_practice.risk_candidate WHERE source_type_code = N'ThirdParty')
    BEGIN
        DELETE FROM grac_practice.risk_source_master WHERE source_type_code = N'ThirdParty';
        PRINT '489 rollback: risk source ThirdParty removed.';
    END
    ELSE
    BEGIN
        UPDATE grac_practice.risk_source_master SET status = N'Inactive', updated_by = N'rollback-489', updated_dt = SYSUTCDATETIME()
         WHERE source_type_code = N'ThirdParty';
        PRINT '489 rollback: risk source ThirdParty is used by candidates -- set Inactive, not removed.';
    END
END
GO

PRINT '489 rollback complete.';
