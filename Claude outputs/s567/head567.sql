CREATE OR ALTER PROCEDURE grac_practice.sp_org_assurance_observation_finding_save
    @organization_id     BIGINT,
    @observation_id      BIGINT,
    @origin_code         NVARCHAR(30)  = NULL,
    @audit_criteria      NVARCHAR(MAX) = NULL,
    @condition_text      NVARCHAR(MAX) = NULL,
    @root_cause          NVARCHAR(MAX) = NULL,
    @risk_impact         NVARCHAR(MAX) = NULL,
    @recommendation      NVARCHAR(MAX) = NULL,
    @management_response NVARCHAR(MAX) = NULL,
    @corrective_action   NVARCHAR(MAX) = NULL,
    @supporting_evidence NVARCHAR(MAX) = NULL,
    @actor               NVARCHAR(100) = 'system'
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;
    DECLARE @status NVARCHAR(60), @cur_origin NVARCHAR(30);
    SELECT @status = os.status_code, @cur_origin = o.observation_origin_code
      FROM grac_practice.org_assurance_observation o
      JOIN grac_practice.org_assurance_observation_status_master os
           ON os.org_assurance_observation_status_id = o.observation_status_id
     WHERE o.org_assurance_observation_id = @observation_id AND o.organization_id = @organization_id AND o.is_active = 1;
    IF @status IS NULL THROW 54053, 'The observation was not found in this organization.', 1;
    IF @status = N'Closed' THROW 54065, 'The observation is closed.', 1;
    SET @origin_code = NULLIF(LTRIM(RTRIM(@origin_code)), N'');
    IF @origin_code IS NOT NULL AND NOT EXISTS (SELECT 1 FROM grac_practice.org_assurance_observation_origin_master
                                                 WHERE origin_code = @origin_code)
        THROW 54062, 'Unknown origin.', 1;
    UPDATE grac_practice.org_assurance_observation
       SET observation_origin_code = ISNULL(@origin_code, @cur_origin),
           audit_criteria = @audit_criteria, condition_text = @condition_text, root_cause = @root_cause,
           risk_impact = @risk_impact, recommendation = @recommendation,
           management_response = @management_response, corrective_action = @corrective_action,
           supporting_evidence = @supporting_evidence,
           updated_by = @actor, updated_dt = SYSUTCDATETIME()
     WHERE org_assurance_observation_id = @observation_id;
END
