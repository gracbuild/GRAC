-- 8m. Raise a finding from a working paper (spec 4.7): only from a paper
-- that is Partially Satisfactory or Unsatisfactory; the auditor writes
-- it -- nothing is raised automatically. Uses the observation's own save
-- (116a), then the spec 4.7 fields.
CREATE OR ALTER PROCEDURE grac_practice.sp_org_assurance_wp_raise_finding
    @organization_id     BIGINT,
    @working_paper_id    BIGINT,
    @title               NVARCHAR(300),
    @description         NVARCHAR(MAX) = NULL,
    @severity_code       NVARCHAR(30)  = N'Medium',
    @owner_employee_id   BIGINT        = NULL,
    @due_date            DATE          = NULL,
    @audit_criteria      NVARCHAR(MAX) = NULL,
    @condition_text      NVARCHAR(MAX) = NULL,
    @root_cause          NVARCHAR(MAX) = NULL,
    @risk_impact         NVARCHAR(MAX) = NULL,
    @recommendation      NVARCHAR(MAX) = NULL,
    @supporting_evidence NVARCHAR(MAX) = NULL,
    @employee_id         BIGINT,
    @actor               NVARCHAR(100) = 'system',
    @observation_id_out  BIGINT OUTPUT
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;
    SET @title = NULLIF(LTRIM(RTRIM(@title)), N'');
    IF @title IS NULL THROW 54062, 'Give the finding a title.', 1;

    DECLARE @exec BIGINT, @q BIGINT, @result NVARCHAR(20), @status NVARCHAR(60), @exec_code NVARCHAR(120),
            @q_code NVARCHAR(120), @q_text NVARCHAR(MAX), @paper_code NVARCHAR(160);
    SELECT @exec = p.org_assurance_execution_id, @q = p.execution_question_id, @result = p.test_result,
           @status = s.status_code, @exec_code = e.execution_code, @q_code = q.question_code,
           @q_text = q.question_text, @paper_code = p.paper_code
      FROM grac_practice.org_assurance_working_paper p
      JOIN grac_practice.org_assurance_execution_question q ON q.execution_question_id = p.execution_question_id
      JOIN grac_practice.org_assurance_execution e ON e.org_assurance_execution_id = p.org_assurance_execution_id
      JOIN grac_practice.org_assurance_execution_status_master s ON s.org_assurance_execution_status_id = e.execution_status_id
     WHERE p.working_paper_id = @working_paper_id AND p.organization_id = @organization_id AND p.is_active = 1;
    IF @exec IS NULL THROW 54053, 'The working paper was not found in this organization.', 1;
    IF @status <> N'InProgress' THROW 54052, 'Findings are raised while the audit is In Progress.', 1;
    IF NOT EXISTS (SELECT 1 FROM grac_practice.fn_org_assurance_wp_roles(@exec, @employee_id) WHERE is_team = 1 OR is_reviewer = 1)
        THROW 54051, 'Only the engagement team raises findings.', 1;
    IF ISNULL(@result, N'') NOT IN (N'PARTIAL', N'UNSATISFACTORY')
        THROW 54063, 'A finding is raised from a Partially Satisfactory or Unsatisfactory working paper.', 1;
    IF @owner_employee_id IS NOT NULL AND NOT EXISTS (SELECT 1 FROM grac_practice.organization_employee
                                                        WHERE employee_id = @owner_employee_id AND organization_id = @organization_id)
        THROW 54062, 'The owner must be an employee of this organization.', 1;

    -- <working paper code>-F; -F2, -F3 ... when used before (codes are
    -- unique per organization over every row).
    DECLARE @base NVARCHAR(115) = LEFT(CONCAT(@paper_code, N'-F'), 115), @code NVARCHAR(120), @k INT = 1;
    SET @code = @base;
    WHILE EXISTS (SELECT 1 FROM grac_practice.org_assurance_observation
                   WHERE organization_id = @organization_id AND observation_code = @code)
    BEGIN
        SET @k += 1;
        SET @code = CONCAT(@base, @k);
    END
    DECLARE @name NVARCHAR(240) = (SELECT employee_name FROM grac_practice.organization_employee
                                    WHERE employee_id = @employee_id AND organization_id = @organization_id);
    BEGIN TRAN;
    EXEC grac_practice.sp_org_assurance_observation_save
         @organization_id            = @organization_id,
         @observation_id             = NULL,
         @execution_id               = @exec,
         @observation_code           = @code,
         @observation_title          = @title,
         @observation_description    = @description,
         @observation_type           = N'Finding',
         @severity_code              = @severity_code,
         @source_question_code       = @q_code,
         @source_question_text       = @q_text,
         @assigned_owner_employee_id = @owner_employee_id,
         @reported_by_employee_id    = @employee_id,
         @reported_by_display_name   = @name,
         @due_date                   = @due_date,
         @actor                      = @actor,
         @observation_id_out         = @observation_id_out OUTPUT;
    UPDATE grac_practice.org_assurance_observation
       SET observation_origin_code = N'TESTING', org_assurance_working_paper_id = @working_paper_id,
           audit_criteria = @audit_criteria, condition_text = @condition_text, root_cause = @root_cause,
           risk_impact = @risk_impact, recommendation = @recommendation, supporting_evidence = @supporting_evidence
     WHERE org_assurance_observation_id = @observation_id_out;
    EXEC grac_practice.sp_org_assurance_wp_log @organization_id = @organization_id, @execution_id = @exec,
         @execution_question_id = @q, @working_paper_id = @working_paper_id, @action_code = N'FindingRaised',
         @to_status = @code, @employee_id = @employee_id, @actor = @actor;
    COMMIT;
END
GO

-- 8n. The finding's spec 4.7 details (Observations -> Finding tab).
CREATE OR ALTER PROCEDURE grac_practice.sp_org_assurance_observation_finding_get
    @organization_id BIGINT,
    @observation_id  BIGINT
AS
BEGIN
    SET NOCOUNT ON;
    SELECT o.org_assurance_observation_id AS ObservationId,
           o.observation_origin_code      AS OriginCode,
           om.origin_name                 AS OriginName,
           o.org_assurance_working_paper_id AS WorkingPaperId,
           p.paper_code                   AS WorkingPaperCode,
           o.audit_criteria               AS AuditCriteria,
           o.condition_text               AS ConditionText,
           o.root_cause                   AS RootCause,
           o.risk_impact                  AS RiskImpact,
           o.recommendation               AS Recommendation,
           o.management_response          AS ManagementResponse,
           o.corrective_action            AS CorrectiveAction,
           o.supporting_evidence          AS SupportingEvidence,
           os.status_code                 AS StatusCode
      FROM grac_practice.org_assurance_observation o
      JOIN grac_practice.org_assurance_observation_status_master os
           ON os.org_assurance_observation_status_id = o.observation_status_id
      LEFT JOIN grac_practice.org_assurance_observation_origin_master om ON om.origin_code = o.observation_origin_code
      LEFT JOIN grac_practice.org_assurance_working_paper p ON p.working_paper_id = o.org_assurance_working_paper_id
     WHERE o.org_assurance_observation_id = @observation_id
       AND o.organization_id = @organization_id
       AND o.is_active = 1;
END
