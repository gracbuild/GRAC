-- 6. Verification
-- =====================================================================
DECLARE @missing NVARCHAR(MAX) = N'';
SELECT @missing = @missing + n.name + N' '
  FROM (VALUES (N'fn_org_assurance_observation_subjects'), (N'sp_custom_gap_generate_from_assurance_observation'),
