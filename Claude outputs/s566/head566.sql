-- 4. The people a responsibility covers (553's rule, one place)
-- =====================================================================
CREATE OR ALTER FUNCTION grac_practice.fn_org_responsibility_holder
(
    @organization_id     BIGINT,
    @responsibility_code NVARCHAR(60)
)
RETURNS TABLE
AS
RETURN
    SELECT e.employee_id, e.employee_code, e.employee_name, e.designation, r.role_id, r.role_name
      FROM grac_practice.organization_employee e
      JOIN grac_practice.organization_role r
           ON r.role_id = e.role_id
     WHERE e.organization_id  = @organization_id
       AND e.status           = N'Active'
       AND e.record_status_id = (SELECT ISNULL((SELECT TOP 1 record_status_id
                                                  FROM grac_practice.record_status_master
                                                 WHERE status_code = 'ACTIVE' OR status_name = 'Active'
                                                 ORDER BY record_status_id), 1))
       AND r.record_status_id = e.record_status_id
       AND EXISTS (SELECT 1
                     FROM grac_practice.organization_role_responsibility x
                     JOIN grac_practice.role_responsibility_master m
                          ON m.role_responsibility_id = x.role_responsibility_id
                    WHERE x.role_id = r.role_id
                      AND x.is_active = 1
                      AND m.is_active = 1
                      AND m.responsibility_code = @responsibility_code);
GO

CREATE OR ALTER PROCEDURE grac_practice.sp_org_responsibility_holder_list
    @organization_id     BIGINT,
    @responsibility_code NVARCHAR(60)
AS
BEGIN
    SET NOCOUNT ON;
    IF @organization_id IS NULL OR NULLIF(LTRIM(RTRIM(@responsibility_code)), N'') IS NULL
        THROW 55100, 'organization_id and responsibility_code are required.', 1;

    -- 566: the rule lives in fn_org_responsibility_holder (also used by the
    -- engagement team checks).
    SELECT h.employee_id   AS EmployeeId,
           h.employee_code AS EmployeeCode,
           h.employee_name AS EmployeeName,
           h.designation   AS Designation,
           h.role_id       AS RoleId,
           h.role_name     AS RoleName
      FROM grac_practice.fn_org_responsibility_holder(@organization_id, @responsibility_code) h
     ORDER BY h.employee_name, h.employee_id;
END
GO

