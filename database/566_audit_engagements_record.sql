-- 5. An engagement's progress (one place)
-- =====================================================================
CREATE OR ALTER FUNCTION grac_practice.fn_org_assurance_engagement_status(@plan_item_id BIGINT)
RETURNS TABLE
AS
RETURN
    SELECT x.definition_count,
           x.started_count,
           x.done_count,
           x.startable_count,
           x.actual_start_dt,
           CASE WHEN x.started_count > 0 AND x.done_count >= x.definition_count THEN x.actual_end_dt END AS actual_end_dt,
           CASE WHEN x.started_count > 0 AND x.done_count >= x.definition_count THEN N'Completed'
                WHEN x.started_count > 0 THEN N'InProgress'
                ELSE N'Planned' END AS progress_status
      FROM (
        SELECT COUNT(*)                AS definition_count,
               ISNULL(SUM(lx.live), 0) AS started_count,
               ISNULL(SUM(lx.done), 0) AS done_count,
               ISNULL(SUM(CASE WHEN lx.live = 0 AND d.active_version_id IS NOT NULL
                                    AND s.status_code <> N'Retired' THEN 1 ELSE 0 END), 0) AS startable_count,
               MIN(lx.actual_start_dt) AS actual_start_dt,
               MAX(lx.actual_end_dt)   AS actual_end_dt
          FROM grac_practice.org_assurance_engagement_definition ed
          JOIN grac_practice.org_assurance_definition d
               ON d.org_assurance_definition_id = ed.org_assurance_definition_id
          JOIN grac_practice.org_assurance_status_master s
               ON s.org_assurance_status_id = d.current_status_id
         CROSS APPLY (
            SELECT ISNULL(MAX(CASE WHEN es.status_code <> N'Cancelled' THEN 1 ELSE 0 END), 0) AS live,
                   ISNULL(MAX(CASE WHEN es.status_code IN (N'Approved', N'Closed') THEN 1 ELSE 0 END), 0) AS done,
                   MIN(CASE WHEN es.status_code <> N'Cancelled' THEN e.actual_start_dt END) AS actual_start_dt,
                   MAX(CASE WHEN es.status_code <> N'Cancelled' THEN e.actual_end_dt END)   AS actual_end_dt
              FROM grac_practice.org_assurance_execution e
              JOIN grac_practice.org_assurance_execution_status_master es
                   ON es.org_assurance_execution_status_id = e.execution_status_id
             WHERE e.org_assurance_plan_item_id  = ed.org_assurance_plan_item_id
               AND e.org_assurance_definition_id = ed.org_assurance_definition_id
               AND e.is_active = 1) lx
         WHERE ed.org_assurance_plan_item_id = @plan_item_id
           AND ed.is_active = 1) x;
GO

-- 565's per-plan progress, now over the engagement status (+ Cancelled).
CREATE OR ALTER FUNCTION grac_practice.fn_org_assurance_engagement_progress(@plan_id BIGINT)
RETURNS TABLE
AS
RETURN
    SELECT i.org_assurance_plan_item_id AS plan_item_id,
           i.org_assurance_programme_id AS programme_id,
           st.definition_count,
           st.started_count,
           st.done_count,
           CASE WHEN i.cancelled_dt IS NOT NULL THEN N'Cancelled' ELSE st.progress_status END AS progress_status
      FROM grac_practice.org_assurance_plan_item i
     CROSS APPLY grac_practice.fn_org_assurance_engagement_status(i.org_assurance_plan_item_id) st
     WHERE i.org_assurance_plan_id = @plan_id
       AND i.is_active = 1;
GO

-- =====================================================================
-- 6. One row per engagement (the list and the detail read this)
--    Status: Cancelled; In Progress / Completed (executions); Draft (an
--    independent engagement not approved yet); Planned.
-- =====================================================================
CREATE OR ALTER FUNCTION grac_practice.fn_org_assurance_engagement_rows(@organization_id BIGINT)
RETURNS TABLE
AS
RETURN
    SELECT i.org_assurance_plan_item_id          AS EngagementId,
           i.organization_id                     AS OrganizationId,
           i.engagement_code                     AS EngagementCode,
           ISNULL(i.engagement_name, i.definition_name) AS EngagementName,
           i.engagement_origin                   AS EngagementOrigin,
           i.item_order                          AS ItemOrder,
           p.org_assurance_plan_id               AS PlanId,
           p.plan_code                           AS PlanCode,
           p.plan_name                           AS PlanName,
           ps.status_code                        AS PlanStatusCode,
           g.org_assurance_programme_id          AS ProgrammeId,
           g.programme_code                      AS ProgrammeCode,
           g.programme_name                      AS ProgrammeName,
           i.audit_subject                       AS AuditSubject,
           i.engagement_objective                AS EngagementObjective,
           i.scope_summary                       AS ScopeSummary,
           i.auditee_role_id                     AS AuditeeRoleId,
           i.auditee_role_name                   AS AuditeeRoleName,
           i.auditee_employee_id                 AS AuditeeEmployeeId,
           i.auditee_name                        AS AuditeeName,
           i.assigned_auditor_role_id            AS LeadAuditorRoleId,
           i.assigned_auditor_role_name          AS LeadAuditorRoleName,
           i.assigned_auditor_employee_id        AS LeadAuditorEmployeeId,
           i.assigned_auditor_name               AS LeadAuditorName,
           (SELECT COUNT(*) FROM grac_practice.org_assurance_engagement_team t
             WHERE t.org_assurance_plan_item_id = i.org_assurance_plan_item_id AND t.is_active = 1) AS TeamCount,
           i.team_remarks                        AS TeamRemarks,
           i.assigned_team_name                  AS TeamText,
           i.engagement_instructions             AS EngagementInstructions,
           i.initiation_source_code              AS InitiationSourceCode,
           im.source_name                        AS InitiationSourceName,
           i.initiation_reason                   AS InitiationReason,
           i.approval_status                     AS ApprovalStatus,
           i.approval_reference                  AS ApprovalReference,
           i.approved_by                         AS ApprovedBy,
           i.approved_dt                         AS ApprovedDt,
           i.cancelled_dt                        AS CancelledDt,
           i.cancelled_by                        AS CancelledBy,
           i.cancel_reason                       AS CancelReason,
           i.scheduled_from                      AS PlannedStart,
           i.scheduled_to                        AS PlannedEnd,
           st.actual_start_dt                    AS ActualStart,
           st.actual_end_dt                      AS ActualEnd,
           i.assigned_branch_id                  AS BranchId,
           i.assigned_branch_name                AS BranchName,
           i.assigned_department_name            AS DepartmentName,
           i.notes                               AS Notes,
           st.definition_count                   AS DefinitionCount,
           (SELECT STRING_AGG(CONVERT(NVARCHAR(MAX), ed.definition_code), N', ') WITHIN GROUP (ORDER BY ed.display_order)
              FROM grac_practice.org_assurance_engagement_definition ed
             WHERE ed.org_assurance_plan_item_id = i.org_assurance_plan_item_id AND ed.is_active = 1) AS DefinitionCodes,
           st.started_count                      AS ExecutionCount,
           st.done_count                         AS ExecutionDoneCount,
           CAST(CASE WHEN i.cancelled_dt IS NULL AND st.startable_count > 0
                      AND (   (i.engagement_origin = N'PLANNED' AND ps.status_code IN (N'Approved', N'Active'))
                           OR (i.engagement_origin = N'INDEPENDENT' AND i.approval_status = N'Approved'))
                     THEN 1 ELSE 0 END AS BIT)   AS CanStart,
           CASE WHEN i.cancelled_dt IS NOT NULL THEN N'Cancelled'
                WHEN st.progress_status IN (N'InProgress', N'Completed') THEN st.progress_status
                WHEN i.engagement_origin = N'INDEPENDENT' AND ISNULL(i.approval_status, N'Draft') <> N'Approved' THEN N'Draft'
                ELSE N'Planned' END              AS EngagementStatus,
           i.entered_by                          AS EnteredBy,
           i.entered_dt                          AS EnteredDt,
           i.updated_by                          AS UpdatedBy,
           i.updated_dt                          AS UpdatedDt
      FROM grac_practice.org_assurance_plan_item i
      LEFT JOIN grac_practice.org_assurance_plan p
             ON p.org_assurance_plan_id = i.org_assurance_plan_id
      LEFT JOIN grac_practice.org_assurance_plan_status_master ps
             ON ps.org_assurance_plan_status_id = p.status_id
      LEFT JOIN grac_practice.org_assurance_plan_programme g
             ON g.org_assurance_programme_id = i.org_assurance_programme_id
      LEFT JOIN grac_practice.org_assurance_engagement_initiation_master im
             ON im.source_code = i.initiation_source_code
     CROSS APPLY grac_practice.fn_org_assurance_engagement_status(i.org_assurance_plan_item_id) st
     WHERE i.organization_id = @organization_id
       AND i.is_active = 1
       AND (p.org_assurance_plan_id IS NULL OR p.is_active = 1);
GO

