-- =====================================================================
-- 1. A finding's Audit Universe subjects
-- =====================================================================
CREATE OR ALTER FUNCTION grac_practice.fn_org_assurance_observation_subjects(@organization_id BIGINT)
RETURNS TABLE
AS
RETURN
    SELECT x.org_assurance_observation_id, x.universe_subject_id, MIN(x.basis) AS link_basis
      FROM (SELECT o.org_assurance_observation_id, i.universe_subject_id, N'ENGAGEMENT' AS basis
              FROM grac_practice.org_assurance_observation o
              JOIN grac_practice.org_assurance_execution e ON e.org_assurance_execution_id = o.org_assurance_execution_id
              JOIN grac_practice.org_assurance_plan_item i ON i.org_assurance_plan_item_id = e.org_assurance_plan_item_id
             WHERE o.organization_id = @organization_id AND o.is_active = 1 AND i.universe_subject_id IS NOT NULL
            UNION
            SELECT f.org_assurance_observation_id, f.universe_subject_id, N'PRACTICE_INSTANCE'
              FROM grac_practice.fn_org_assurance_universe_subject_findings(@organization_id) f) x
     GROUP BY x.org_assurance_observation_id, x.universe_subject_id;
GO

