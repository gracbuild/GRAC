-- 3a. A subject's practice instances: its Suggested / Confirmed
--     PRACTICE_INSTANCE mappings (the strongest status when duplicated).
CREATE OR ALTER FUNCTION grac_practice.fn_org_assurance_universe_subject_instances(@organization_id BIGINT)
RETURNS TABLE
AS
RETURN
    SELECT m.universe_subject_id, pi.practice_instance_id, pi.practice_id, MAX(m.mapping_status) AS mapping_status
      FROM grac_practice.org_assurance_universe_mapping m
      JOIN grac_practice.practice_instance pi
           ON pi.practice_instance_id = TRY_CAST(m.record_key AS BIGINT) AND pi.organization_id = @organization_id
     WHERE m.mapping_level = N'PRACTICE_INSTANCE'
       AND m.mapping_status IN (N'SUGGESTED', N'CONFIRMED')
     GROUP BY m.universe_subject_id, pi.practice_instance_id, pi.practice_id;
GO

-- 3b. A subject's gaps: gaps whose source is one of its instances, or that
--     are mapped to one (custom_gap_practice_map, Active).
CREATE OR ALTER FUNCTION grac_practice.fn_org_assurance_universe_subject_gaps(@organization_id BIGINT)
RETURNS TABLE
AS
RETURN
    SELECT i.universe_subject_id, g.custom_gap_id, MIN(i.practice_instance_id) AS practice_instance_id
      FROM grac_practice.custom_gap g
      JOIN grac_practice.fn_org_assurance_universe_subject_instances(@organization_id) i
           ON (g.source_reference_type = N'PracticeInstance' AND g.source_reference_id = i.practice_instance_id)
           OR EXISTS (SELECT 1
                        FROM grac_practice.custom_gap_practice_map gm
                        JOIN grac_practice.record_status_master rs
                          ON rs.record_status_id = gm.record_status_id AND rs.status_code = N'Active'
                       WHERE gm.custom_gap_id = g.custom_gap_id AND gm.practice_instance_id = i.practice_instance_id)
     WHERE g.organization_id = @organization_id
     GROUP BY i.universe_subject_id, g.custom_gap_id;
GO

-- 3c. A subject's enterprise risks: its Suggested / Confirmed RISK mappings.
CREATE OR ALTER FUNCTION grac_practice.fn_org_assurance_universe_subject_risks(@organization_id BIGINT)
RETURNS TABLE
AS
RETURN
    SELECT m.universe_subject_id, rr.risk_register_id, m.mapping_status, m.mapping_source, m.suggestion_basis
      FROM grac_practice.org_assurance_universe_mapping m
      JOIN grac_practice.risk_register rr
           ON rr.risk_register_id = TRY_CAST(m.record_key AS BIGINT) AND rr.organization_id = @organization_id
     WHERE m.mapping_level = N'RISK'
       AND m.mapping_status IN (N'SUGGESTED', N'CONFIRMED');
GO

-- 3d. A subject's previous audit findings: active observations recorded
--     against one of its practice instances (execution entity
--     PRACTICE_INSTANCE).
CREATE OR ALTER FUNCTION grac_practice.fn_org_assurance_universe_subject_findings(@organization_id BIGINT)
RETURNS TABLE
AS
RETURN
    SELECT x.universe_subject_id, o.org_assurance_observation_id, ee.org_assurance_execution_entity_id
      FROM grac_practice.org_assurance_observation o
      JOIN grac_practice.org_assurance_execution_entity ee
           ON ee.org_assurance_execution_entity_id = o.org_assurance_execution_entity_id
          AND ee.dimension_code = N'PRACTICE_INSTANCE'
      JOIN grac_practice.fn_org_assurance_universe_subject_instances(@organization_id) x
           ON x.practice_instance_id = ee.entity_id
     WHERE o.organization_id = @organization_id AND o.is_active = 1;
GO

-- 3e. A subject's last audit: its latest completed, active engagement
--     linked to it; the result is that engagement's latest approved /
--     closed execution's score band; its first audit definition.
CREATE OR ALTER FUNCTION grac_practice.fn_org_assurance_universe_subject_audit(@organization_id BIGINT)
RETURNS TABLE
AS
RETURN
    SELECT s.universe_subject_id, la.EngagementId AS last_engagement_id, la.EngagementCode AS last_engagement_code,
           la.ActualEnd AS last_audit_dt, lr.last_result, ld.definition_id, ld.definition_name
      FROM grac_practice.org_assurance_universe_subject s
     CROSS APPLY (SELECT TOP (1) r.EngagementId, r.EngagementCode, r.ActualEnd
                    FROM grac_practice.fn_org_assurance_engagement_rows(@organization_id) r
                    JOIN grac_practice.org_assurance_plan_item i ON i.org_assurance_plan_item_id = r.EngagementId
                   WHERE i.universe_subject_id = s.universe_subject_id AND i.is_active = 1
                     AND r.EngagementStatus = N'Completed'
                   ORDER BY r.ActualEnd DESC, r.EngagementId DESC) la
     OUTER APPLY (SELECT TOP (1) ISNULL(e.score_band_name, N'') +
                                 CASE WHEN e.score_pct IS NOT NULL
                                      THEN N' (' + CONVERT(NVARCHAR(20), CAST(e.score_pct AS DECIMAL(6,1))) + N'%)' ELSE N'' END
                                 AS last_result
                    FROM grac_practice.org_assurance_execution e
                    JOIN grac_practice.org_assurance_execution_status_master es
                         ON es.org_assurance_execution_status_id = e.execution_status_id
                   WHERE e.org_assurance_plan_item_id = la.EngagementId AND e.is_active = 1
                     AND es.status_code IN (N'Approved', N'Closed')
                   ORDER BY e.actual_end_dt DESC, e.org_assurance_execution_id DESC) lr
     OUTER APPLY (SELECT TOP (1) ed.org_assurance_definition_id AS definition_id, ed.definition_name
                    FROM grac_practice.org_assurance_engagement_definition ed
                   WHERE ed.org_assurance_plan_item_id = la.EngagementId AND ed.is_active = 1
                   ORDER BY ed.display_order, ed.org_assurance_definition_id) ld
     WHERE s.organization_id = @organization_id;
GO
