-- =====================================================================
-- 5. The pickers' lists: the organization's active practices and
--    practice instances (controls come from the 534 statement tree).
-- =====================================================================
CREATE OR ALTER PROCEDURE grac_practice.sp_org_assurance_mapping_options
    @organization_id BIGINT
AS
BEGIN
    SET NOCOUNT ON;
    IF @organization_id IS NULL
        THROW 53602, 'organization_id is required.', 1;

    SELECT p.practice_id   AS Id,
           p.practice_code AS Code,
           p.practice_name AS Name,
           (SELECT COUNT(*) FROM grac_practice.practice_instance pi
             WHERE pi.practice_id = p.practice_id
               AND pi.organization_id = @organization_id
               AND pi.status = N'Active') AS InstanceCount
      FROM grac_practice.practice p
     WHERE p.organization_id = @organization_id
       AND p.status = N'Active'
     ORDER BY p.practice_code, p.practice_name;

    SELECT pi.practice_instance_id AS Id,
           pi.instance_code        AS Code,
           pi.instance_name        AS Name,
           pi.practice_id          AS PracticeId,
           p.practice_code         AS PracticeCode
      FROM grac_practice.practice_instance pi
      LEFT JOIN grac_practice.practice p ON p.practice_id = pi.practice_id
     WHERE pi.organization_id = @organization_id
       AND pi.status = N'Active'
     ORDER BY p.practice_code, pi.instance_code, pi.instance_name;
END
GO

