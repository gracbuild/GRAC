-- 7b. The engagement list (filters, paging)
-- =====================================================================
CREATE OR ALTER PROCEDURE grac_practice.sp_org_assurance_engagement_list
    @organization_id BIGINT,
    @status          NVARCHAR(30)  = NULL,   -- Draft / Planned / InProgress / Completed / Cancelled
    @origin          NVARCHAR(20)  = NULL,   -- PLANNED / INDEPENDENT
    @plan_id         BIGINT        = NULL,
    @search          NVARCHAR(200) = NULL,
    @page            INT = 1,
    @page_size       INT = 25
AS
BEGIN
    SET NOCOUNT ON;
    IF @organization_id IS NULL
        THROW 53901, 'organization_id is required.', 1;
    IF @page IS NULL OR @page < 1 SET @page = 1;
    IF @page_size IS NULL OR @page_size < 1 SET @page_size = 25;
    IF @page_size > 200 SET @page_size = 200;
    DECLARE @offset INT = (@page - 1) * @page_size;

    SELECT *
      INTO #eng
      FROM grac_practice.fn_org_assurance_engagement_rows(@organization_id) r
     WHERE (@status IS NULL OR @status = N'' OR r.EngagementStatus = @status)
       AND (@origin IS NULL OR @origin = N'' OR r.EngagementOrigin = @origin)
       AND (@plan_id IS NULL OR r.PlanId = @plan_id)
       AND (@search IS NULL OR @search = N''
            OR r.EngagementCode LIKE N'%' + @search + N'%'
            OR r.EngagementName LIKE N'%' + @search + N'%'
            OR r.AuditSubject   LIKE N'%' + @search + N'%'
            OR r.LeadAuditorName LIKE N'%' + @search + N'%'
            OR r.DefinitionCodes LIKE N'%' + @search + N'%');

    SELECT CAST(COUNT_BIG(1) AS BIGINT) AS TotalCount,
           CAST(@page AS INT)           AS PageNumber,
           CAST(@page_size AS INT)      AS PageSize
      FROM #eng;

    SELECT *
      FROM #eng
     ORDER BY CASE EngagementStatus WHEN N'Draft' THEN 0 WHEN N'Planned' THEN 1 WHEN N'InProgress' THEN 2
                                    WHEN N'Completed' THEN 3 ELSE 4 END,
              PlannedStart, EngagementCode, EngagementId
    OFFSET @offset ROWS FETCH NEXT @page_size ROWS ONLY;
END
