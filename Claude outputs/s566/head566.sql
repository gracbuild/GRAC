-- 7b. The engagement list (filters, paging)
-- =====================================================================
CREATE OR ALTER PROCEDURE grac_practice.sp_org_assurance_engagement_list
    @organization_id BIGINT,
    @status          NVARCHAR(30)  = NULL,   -- Draft / Planned / InProgress / Completed / Cancelled
    @origin          NVARCHAR(20)  = NULL,   -- PLANNED / INDEPENDENT
    @plan_id         BIGINT        = NULL,
    @search          NVARCHAR(200) = NULL,
    @page            INT = 1,
    @page_size       INT = 25
AS
BEGIN
    SET NOCOUNT ON;
    IF @organization_id IS NULL
        THROW 53901, 'organization_id is required.', 1;
    IF @page IS NULL OR @page < 1 SET @page = 1;
    IF @page_size IS NULL OR @page_size < 1 SET @page_size = 25;
    IF @page_size > 200 SET @page_size = 200;
    DECLARE @offset INT = (@page - 1) * @page_size;

    SELECT *
      INTO #eng
      FROM grac_practice.fn_org_assurance_engagement_rows(@organization_id) r
     WHERE (@status IS NULL OR @status = N'' OR r.EngagementStatus = @status)
       AND (@origin IS NULL OR @origin = N'' OR r.EngagementOrigin = @origin)
       AND (@plan_id IS NULL OR r.PlanId = @plan_id)
       AND (@search IS NULL OR @search = N''
            OR r.EngagementCode LIKE N'%' + @search + N'%'
            OR r.EngagementName LIKE N'%' + @search + N'%'
            OR r.AuditSubject   LIKE N'%' + @search + N'%'
            OR r.LeadAuditorName LIKE N'%' + @search + N'%'
            OR r.DefinitionCodes LIKE N'%' + @search + N'%');

    SELECT CAST(COUNT_BIG(1) AS BIGINT) AS TotalCount,
           CAST(@page AS INT)           AS PageNumber,
           CAST(@page_size AS INT)      AS PageSize
      FROM #eng;

    SELECT *
      FROM #eng
     ORDER BY CASE EngagementStatus WHEN N'Draft' THEN 0 WHEN N'Planned' THEN 1 WHEN N'InProgress' THEN 2
                                    WHEN N'Completed' THEN 3 ELSE 4 END,
              PlannedStart, EngagementCode, EngagementId
    OFFSET @offset ROWS FETCH NEXT @page_size ROWS ONLY;
END
GO

-- =====================================================================
-- 7c. One engagement: the row, its audits, its team (active)
-- =====================================================================
CREATE OR ALTER PROCEDURE grac_practice.sp_org_assurance_engagement_get
    @organization_id BIGINT,
    @plan_item_id    BIGINT
AS
BEGIN
    SET NOCOUNT ON;
    IF @organization_id IS NULL OR @plan_item_id IS NULL
        THROW 53902, 'organization_id and plan_item_id are required.', 1;

    SELECT * FROM grac_practice.fn_org_assurance_engagement_rows(@organization_id) r
     WHERE r.EngagementId = @plan_item_id;

    SELECT ed.org_assurance_definition_id AS DefinitionId,
           ed.definition_code             AS DefinitionCode,
           ed.definition_name             AS DefinitionName,
           ed.display_order               AS DisplayOrder
      FROM grac_practice.org_assurance_engagement_definition ed
      JOIN grac_practice.org_assurance_plan_item i ON i.org_assurance_plan_item_id = ed.org_assurance_plan_item_id
     WHERE ed.org_assurance_plan_item_id = @plan_item_id
       AND i.organization_id = @organization_id
       AND ed.is_active = 1
     ORDER BY ed.display_order;

    EXEC grac_practice.sp_org_assurance_engagement_team_list
         @organization_id = @organization_id, @plan_item_id = @plan_item_id, @include_history = 0;
END
GO

-- =====================================================================
-- 7d. An engagement's team (with the removed rows when asked: the trail)
-- =====================================================================
CREATE OR ALTER PROCEDURE grac_practice.sp_org_assurance_engagement_team_list
    @organization_id BIGINT,
    @plan_item_id    BIGINT,
    @include_history BIT = 0
AS
BEGIN
    SET NOCOUNT ON;
    SELECT t.engagement_team_id   AS TeamMemberId,
           t.team_role            AS TeamRole,
           t.employee_id          AS EmployeeId,
           t.member_name          AS MemberName,
           t.member_designation   AS Designation,
           t.member_role_name     AS RoleName,
           t.external_organisation AS ExternalOrganisation,
           t.is_active            AS IsActive,
           t.entered_by           AS AddedBy,
           t.entered_dt           AS AddedDt,
           t.removed_by           AS RemovedBy,
           t.removed_dt           AS RemovedDt
      FROM grac_practice.org_assurance_engagement_team t
     WHERE t.org_assurance_plan_item_id = @plan_item_id
       AND t.organization_id = @organization_id
       AND (t.is_active = 1 OR ISNULL(@include_history, 0) = 1)
     ORDER BY t.is_active DESC,
              CASE t.team_role WHEN N'LEAD' THEN 0 WHEN N'MEMBER' THEN 1 WHEN N'REVIEWER' THEN 2
                               WHEN N'SME' THEN 3 ELSE 4 END,
              t.member_name, t.engagement_team_id;
END
GO

-- =====================================================================
-- 7e. Apply a team (internal: called inside the caller's transaction).
--     The LEAD is the engagement's lead auditor; @team_json NULL leaves
--     the other roles as they are. A removed member stays as a row with
--     removed_by / removed_dt (the trail); a new pick must be eligible --
--     members and the reviewer auditors (553), subject matter experts any
--     active employee; one reviewer at most; externals need a name.
--     @team_json: [{ "teamRole": "MEMBER", "employeeId": 12 },
--                  { "teamRole": "EXTERNAL", "name": "...", "organisation": "..." }]
-- =====================================================================
CREATE OR ALTER PROCEDURE grac_practice.sp_org_assurance_engagement_team_apply
    @organization_id BIGINT,
    @plan_item_id    BIGINT,
    @team_json       NVARCHAR(MAX) = NULL,
    @actor           NVARCHAR(100) = 'system'
AS
BEGIN
    SET NOCOUNT ON;
    DECLARE @lead BIGINT, @lead_name NVARCHAR(240);
    SELECT @lead = assigned_auditor_employee_id, @lead_name = assigned_auditor_name
      FROM grac_practice.org_assurance_plan_item
     WHERE org_assurance_plan_item_id = @plan_item_id AND organization_id = @organization_id;

    DECLARE @in TABLE (team_role NVARCHAR(20) NULL, employee_id BIGINT NULL,
                       member_name NVARCHAR(240) NULL, external_organisation NVARCHAR(240) NULL);
    IF @team_json IS NOT NULL
    BEGIN
        IF ISJSON(@team_json) <> 1
            THROW 53959, 'Audit team: the list is not valid.', 1;
        INSERT @in (team_role, employee_id, member_name, external_organisation)
        SELECT UPPER(LTRIM(RTRIM(x.teamRole))), x.employeeId,
               LEFT(NULLIF(LTRIM(RTRIM(x.name)), N''), 240),
               LEFT(NULLIF(LTRIM(RTRIM(x.organisation)), N''), 240)
          FROM OPENJSON(@team_json)
               WITH (teamRole NVARCHAR(20) '$.teamRole', employeeId BIGINT '$.employeeId',
                     name NVARCHAR(MAX) '$.name', organisation NVARCHAR(MAX) '$.organisation') x;
        IF EXISTS (SELECT 1 FROM @in WHERE team_role IS NULL
                      OR team_role NOT IN (N'MEMBER', N'SME', N'REVIEWER', N'EXTERNAL'))
            THROW 53959, 'Audit team: unknown team role.', 1;
        IF EXISTS (SELECT 1 FROM @in WHERE team_role <> N'EXTERNAL' AND employee_id IS NULL)
            THROW 53959, 'Audit team: a member is missing.', 1;
        IF EXISTS (SELECT 1 FROM @in WHERE team_role = N'EXTERNAL' AND member_name IS NULL)
            THROW 53959, 'Every external auditor needs a name.', 1;
        IF (SELECT COUNT(DISTINCT employee_id) FROM @in WHERE team_role = N'REVIEWER') > 1
            THROW 53959, 'An engagement has one reviewer.', 1;
        -- The lead is the lead, not also a member.
        DELETE FROM @in WHERE team_role = N'MEMBER' AND employee_id = @lead;
        -- New picks only: a member kept from before stays whatever their role now.
        IF EXISTS (SELECT 1 FROM @in i
                    WHERE i.team_role IN (N'MEMBER', N'REVIEWER')
                      AND NOT EXISTS (SELECT 1 FROM grac_practice.fn_org_responsibility_holder(@organization_id, N'AUDITOR') h
                                       WHERE h.employee_id = i.employee_id)
                      AND NOT EXISTS (SELECT 1 FROM grac_practice.org_assurance_engagement_team t
                                       WHERE t.org_assurance_plan_item_id = @plan_item_id AND t.is_active = 1
                                         AND t.team_role = i.team_role AND t.employee_id = i.employee_id))
            THROW 53954, 'Team members and the reviewer must be auditors (a role with the Auditor responsibility in Role Master).', 1;
        IF EXISTS (SELECT 1 FROM @in i
                    WHERE i.team_role = N'SME'
                      AND NOT EXISTS (SELECT 1 FROM grac_practice.organization_employee e
                                       WHERE e.employee_id = i.employee_id
                                         AND e.organization_id = @organization_id AND e.status = N'Active')
                      AND NOT EXISTS (SELECT 1 FROM grac_practice.org_assurance_engagement_team t
                                       WHERE t.org_assurance_plan_item_id = @plan_item_id AND t.is_active = 1
                                         AND t.team_role = N'SME' AND t.employee_id = i.employee_id))
            THROW 53959, 'A subject matter expert must be an active employee of the organization.', 1;
    END

    DECLARE @want TABLE (team_role NVARCHAR(20), employee_id BIGINT NULL,
                         member_name NVARCHAR(240) NULL, external_organisation NVARCHAR(240) NULL);
    IF @lead IS NOT NULL INSERT @want VALUES (N'LEAD', @lead, NULL, NULL);
    INSERT @want
    SELECT DISTINCT team_role, CASE WHEN team_role = N'EXTERNAL' THEN NULL ELSE employee_id END,
           CASE WHEN team_role = N'EXTERNAL' THEN member_name END,
           CASE WHEN team_role = N'EXTERNAL' THEN external_organisation END
      FROM @in;

    -- Removed: kept as the trail.
    UPDATE t
       SET is_active = 0, removed_by = @actor, removed_dt = SYSUTCDATETIME()
      FROM grac_practice.org_assurance_engagement_team t
     WHERE t.org_assurance_plan_item_id = @plan_item_id
       AND t.is_active = 1
       AND (t.team_role = N'LEAD' OR @team_json IS NOT NULL)
       AND NOT EXISTS (SELECT 1 FROM @want w
                        WHERE w.team_role = t.team_role
                          AND (   (w.team_role <> N'EXTERNAL' AND w.employee_id = t.employee_id)
                               OR (w.team_role = N'EXTERNAL' AND w.member_name = t.member_name
                                   AND ISNULL(w.external_organisation, N'') = ISNULL(t.external_organisation, N''))));

    -- Added: name, designation and role as they are now (kept for history).
    INSERT INTO grac_practice.org_assurance_engagement_team
        (org_assurance_plan_item_id, organization_id, team_role, employee_id,
         member_name, member_designation, member_role_name, external_organisation,
         is_active, entered_by, entered_dt)
    SELECT @plan_item_id, @organization_id, w.team_role, w.employee_id,
           COALESCE(e.employee_name, w.member_name, CASE WHEN w.team_role = N'LEAD' THEN @lead_name END),
           e.designation, r.role_name, w.external_organisation,
           1, @actor, SYSUTCDATETIME()
      FROM @want w
      LEFT JOIN grac_practice.organization_employee e
             ON e.employee_id = w.employee_id AND e.organization_id = @organization_id
      LEFT JOIN grac_practice.organization_role r ON r.role_id = e.role_id
     WHERE (w.team_role = N'LEAD' OR @team_json IS NOT NULL)
       AND NOT EXISTS (SELECT 1 FROM grac_practice.org_assurance_engagement_team t
                        WHERE t.org_assurance_plan_item_id = @plan_item_id
                          AND t.is_active = 1
                          AND t.team_role = w.team_role
                          AND (   (w.team_role <> N'EXTERNAL' AND w.employee_id = t.employee_id)
                               OR (w.team_role = N'EXTERNAL' AND w.member_name = t.member_name
                                   AND ISNULL(w.external_organisation, N'') = ISNULL(t.external_organisation, N''))));
END
GO

-- =====================================================================
-- 7f. Change the team (any time until the engagement is cancelled or
--     completed; the lead is changed on the engagement itself)
-- =====================================================================
CREATE OR ALTER PROCEDURE grac_practice.sp_org_assurance_engagement_team_save
    @organization_id BIGINT,
    @plan_item_id    BIGINT,
    @team_json       NVARCHAR(MAX),
    @team_remarks    NVARCHAR(2000) = NULL,
    @actor           NVARCHAR(100) = 'system'
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;
    IF @organization_id IS NULL OR @plan_item_id IS NULL
        THROW 53902, 'organization_id and plan_item_id are required.', 1;
    DECLARE @cancelled DATETIME2, @found BIT = 0;
    SELECT @cancelled = cancelled_dt, @found = 1
      FROM grac_practice.org_assurance_plan_item
     WHERE org_assurance_plan_item_id = @plan_item_id AND organization_id = @organization_id AND is_active = 1;
    IF @found = 0 THROW 53915, 'Engagement not found.', 1;
    IF @cancelled IS NOT NULL THROW 53957, 'The engagement is cancelled.', 1;
    IF EXISTS (SELECT 1 FROM grac_practice.fn_org_assurance_engagement_status(@plan_item_id) s
                WHERE s.progress_status = N'Completed')
        THROW 53957, 'The engagement is completed; its team is kept as it was.', 1;

    BEGIN TRAN;
    UPDATE grac_practice.org_assurance_plan_item
       SET team_remarks = @team_remarks, updated_by = @actor, updated_dt = SYSUTCDATETIME()
     WHERE org_assurance_plan_item_id = @plan_item_id;
    EXEC grac_practice.sp_org_assurance_engagement_team_apply
         @organization_id = @organization_id, @plan_item_id = @plan_item_id,
         @team_json = @team_json, @actor = @actor;
    COMMIT;
END
GO

-- =====================================================================
-- 7g. Approve an independent engagement (by authority)
-- =====================================================================
CREATE OR ALTER PROCEDURE grac_practice.sp_org_assurance_engagement_approve
    @organization_id    BIGINT,
    @plan_item_id       BIGINT,
    @approval_reference NVARCHAR(200) = NULL,
    @actor              NVARCHAR(100) = 'system'
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;
    DECLARE @origin NVARCHAR(20), @approval NVARCHAR(20), @cancelled DATETIME2, @ref NVARCHAR(200);
    SELECT @origin = engagement_origin, @approval = approval_status, @cancelled = cancelled_dt,
           @ref = approval_reference
      FROM grac_practice.org_assurance_plan_item
     WHERE org_assurance_plan_item_id = @plan_item_id AND organization_id = @organization_id AND is_active = 1;
    IF @origin IS NULL THROW 53915, 'Engagement not found.', 1;
    IF @cancelled IS NOT NULL THROW 53957, 'The engagement is cancelled.', 1;
    IF @origin <> N'INDEPENDENT'
        THROW 53956, 'A planned engagement is approved with its plan.', 1;
    IF @approval = N'Approved'
        THROW 53956, 'The engagement is already approved.', 1;
    IF NULLIF(LTRIM(RTRIM(ISNULL(@approval_reference, @ref))), N'') IS NULL
        THROW 53956, 'Give the approval reference (the authority''s decision).', 1;

    UPDATE grac_practice.org_assurance_plan_item
       SET approval_status    = N'Approved',
           approval_reference = LEFT(LTRIM(RTRIM(ISNULL(NULLIF(LTRIM(RTRIM(@approval_reference)), N''), @ref))), 200),
           approved_by        = @actor,
           approved_dt        = SYSUTCDATETIME(),
           updated_by         = @actor,
           updated_dt         = SYSUTCDATETIME()
     WHERE org_assurance_plan_item_id = @plan_item_id;
END
GO

-- =====================================================================
-- 7h. Cancel an engagement (no execution of it left, reason required)
-- =====================================================================
CREATE OR ALTER PROCEDURE grac_practice.sp_org_assurance_engagement_cancel
    @organization_id BIGINT,
    @plan_item_id    BIGINT,
    @reason          NVARCHAR(2000),
    @actor           NVARCHAR(100) = 'system'
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;
    IF NULLIF(LTRIM(RTRIM(@reason)), N'') IS NULL
        THROW 53958, 'Give the reason for cancelling the engagement.', 1;
    DECLARE @cancelled DATETIME2, @found BIT = 0;
    SELECT @cancelled = cancelled_dt, @found = 1
      FROM grac_practice.org_assurance_plan_item
     WHERE org_assurance_plan_item_id = @plan_item_id AND organization_id = @organization_id AND is_active = 1;
    IF @found = 0 THROW 53915, 'Engagement not found.', 1;
    IF @cancelled IS NOT NULL THROW 53957, 'The engagement is already cancelled.', 1;
    IF EXISTS (SELECT 1 FROM grac_practice.org_assurance_execution e
                 JOIN grac_practice.org_assurance_execution_status_master es
                      ON es.org_assurance_execution_status_id = e.execution_status_id
                WHERE e.org_assurance_plan_item_id = @plan_item_id
                  AND e.is_active = 1 AND es.status_code <> N'Cancelled')
        THROW 53958, 'The engagement has executions. Cancel them first (Executions), then the engagement.', 1;

    UPDATE grac_practice.org_assurance_plan_item
       SET cancelled_dt = SYSUTCDATETIME(), cancelled_by = @actor,
           cancel_reason = LEFT(LTRIM(RTRIM(@reason)), 2000),
           updated_by = @actor, updated_dt = SYSUTCDATETIME()
     WHERE org_assurance_plan_item_id = @plan_item_id;
END
GO

-- =====================================================================
-- 7i. Delete an independent engagement while it is a Draft (a planned
--     one is removed from its plan, as before)
-- =====================================================================
CREATE OR ALTER PROCEDURE grac_practice.sp_org_assurance_engagement_delete
    @organization_id BIGINT,
    @plan_item_id    BIGINT,
    @actor           NVARCHAR(100) = 'system'
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;
    DECLARE @origin NVARCHAR(20), @approval NVARCHAR(20);
    SELECT @origin = engagement_origin, @approval = approval_status
      FROM grac_practice.org_assurance_plan_item
     WHERE org_assurance_plan_item_id = @plan_item_id AND organization_id = @organization_id AND is_active = 1;
    IF @origin IS NULL THROW 53915, 'Engagement not found.', 1;
    IF @origin <> N'INDEPENDENT'
        THROW 53956, 'A planned engagement is removed from its plan (Audit Plans).', 1;
    IF ISNULL(@approval, N'Draft') = N'Approved'
        THROW 53956, 'An approved engagement is cancelled, not deleted.', 1;
    IF EXISTS (SELECT 1 FROM grac_practice.org_assurance_execution e
                WHERE e.org_assurance_plan_item_id = @plan_item_id AND e.is_active = 1)
        THROW 53936, 'This engagement already has an execution.', 1;

    UPDATE grac_practice.org_assurance_plan_item
       SET is_active = 0, updated_by = @actor, updated_dt = SYSUTCDATETIME()
     WHERE org_assurance_plan_item_id = @plan_item_id;
END
