-- 7b. A plan's programmes, with planned vs actual
-- =====================================================================
CREATE OR ALTER PROCEDURE grac_practice.sp_org_assurance_plan_programme_list
    @organization_id BIGINT,
    @plan_id         BIGINT
AS
BEGIN
    SET NOCOUNT ON;
    IF @organization_id IS NULL OR @plan_id IS NULL
        THROW 53902, 'organization_id and plan_id are required.', 1;
    IF NOT EXISTS (SELECT 1 FROM grac_practice.org_assurance_plan
                    WHERE org_assurance_plan_id = @plan_id AND organization_id = @organization_id)
        THROW 53908, 'Plan belongs to a different organization.', 1;

    SELECT g.org_assurance_programme_id AS ProgrammeId,
           g.org_assurance_plan_id      AS PlanId,
           g.programme_code             AS ProgrammeCode,
           g.programme_name             AS ProgrammeName,
           g.objective                  AS Objective,
           g.planning_methodology_id    AS PlanningMethodologyId,
           g.methodology_code           AS MethodologyCode,
           g.methodology_name           AS MethodologyName,
           g.owner_role_id              AS OwnerRoleId,
           g.owner_role_name            AS OwnerRoleName,
           g.owner_employee_id          AS OwnerEmployeeId,
           g.owner_display_name         AS OwnerDisplayName,
           g.display_order              AS DisplayOrder,
           g.is_default                 AS IsDefault,
           ISNULL(pr.engagement_count, 0) AS EngagementCount,
           ISNULL(pr.started_count, 0)    AS EngagementInProgressCount,
           ISNULL(pr.done_count, 0)       AS EngagementCompletedCount
      FROM grac_practice.org_assurance_plan_programme g
      OUTER APPLY (
          SELECT COUNT(*) AS engagement_count,
                 SUM(CASE WHEN f.progress_status = N'InProgress' THEN 1 ELSE 0 END) AS started_count,
                 SUM(CASE WHEN f.progress_status = N'Completed'  THEN 1 ELSE 0 END) AS done_count
            FROM grac_practice.fn_org_assurance_engagement_progress(@plan_id) f
           WHERE f.programme_id = g.org_assurance_programme_id) pr
     WHERE g.org_assurance_plan_id = @plan_id
       AND g.organization_id = @organization_id
       AND g.is_active = 1
     ORDER BY g.display_order, g.programme_name, g.org_assurance_programme_id;
END
GO

-- =====================================================================
-- 7c. Save a programme (the plan Draft / Submitted, as its engagements)
-- =====================================================================
CREATE OR ALTER PROCEDURE grac_practice.sp_org_assurance_plan_programme_save
    @organization_id         BIGINT,
    @plan_id                 BIGINT,
    @programme_id            BIGINT        = NULL,
    @programme_name          NVARCHAR(240),
    @objective               NVARCHAR(MAX) = NULL,
    @planning_methodology_id INT           = NULL,
    @owner_role_id           BIGINT        = NULL,
    @owner_role_name         NVARCHAR(120) = NULL,
    @owner_employee_id       BIGINT        = NULL,
    @owner_display_name      NVARCHAR(240) = NULL,
    @display_order           INT           = NULL,
    @actor                   NVARCHAR(100) = 'system',
    @programme_id_out        BIGINT OUTPUT
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;

    IF @organization_id IS NULL OR @plan_id IS NULL
        THROW 53902, 'organization_id and plan_id are required.', 1;
    IF NULLIF(LTRIM(RTRIM(@programme_name)), N'') IS NULL
        THROW 53947, 'The programme needs a name.', 1;

    DECLARE @plan_status NVARCHAR(60), @plan_code NVARCHAR(80);
    SELECT @plan_status = s.status_code, @plan_code = p.plan_code
      FROM grac_practice.org_assurance_plan p
      JOIN grac_practice.org_assurance_plan_status_master s
           ON s.org_assurance_plan_status_id = p.status_id
     WHERE p.org_assurance_plan_id = @plan_id
       AND p.organization_id = @organization_id
       AND p.is_active = 1;
    IF @plan_status IS NULL THROW 53907, 'Plan not found.', 1;
    IF @plan_status NOT IN (N'Draft', N'Submitted')
        THROW 53909, 'Programmes can be changed only while the plan is Draft or Submitted.', 1;

    DECLARE @m_code NVARCHAR(40), @m_name NVARCHAR(120);
    SELECT @m_code = methodology_code, @m_name = methodology_name
      FROM grac_practice.org_assurance_planning_methodology_master
     WHERE planning_methodology_id = @planning_methodology_id AND is_active = 1;
    IF @m_code IS NULL
        THROW 53948, 'Pick the planning methodology of the programme.', 1;

    -- 121 hybrid ownership resolver (as the plan owner).
    IF @owner_role_id IS NOT NULL
       AND (@owner_role_name IS NULL OR LEN(LTRIM(RTRIM(@owner_role_name))) = 0)
        SELECT @owner_role_name = role_name
        FROM grac_practice.organization_role
        WHERE role_id = @owner_role_id AND organization_id = @organization_id;
    IF @owner_role_id IS NOT NULL AND @owner_employee_id IS NULL
        EXEC grac_practice.sp_org_role_primary_holder_pick
             @organization_id   = @organization_id,
             @role_id           = @owner_role_id,
             @employee_id_out   = @owner_employee_id  OUTPUT,
             @employee_name_out = @owner_display_name OUTPUT;
    IF @owner_employee_id IS NOT NULL AND @owner_role_id IS NULL
        SELECT @owner_role_id   = e.role_id,
               @owner_role_name = r.role_name
        FROM grac_practice.organization_employee e
        LEFT JOIN grac_practice.organization_role r ON r.role_id = e.role_id
        WHERE e.employee_id = @owner_employee_id AND e.organization_id = @organization_id;
    IF @owner_employee_id IS NOT NULL
       AND (@owner_display_name IS NULL OR LEN(LTRIM(RTRIM(@owner_display_name))) = 0)
        SELECT @owner_display_name = employee_name
        FROM grac_practice.organization_employee
        WHERE employee_id = @owner_employee_id;

    BEGIN TRAN;
    IF @programme_id IS NULL
    BEGIN
        INSERT INTO grac_practice.org_assurance_plan_programme
            (org_assurance_plan_id, organization_id, programme_code, programme_name, objective,
             planning_methodology_id, methodology_code, methodology_name,
             owner_role_id, owner_role_name, owner_employee_id, owner_display_name,
             display_order, is_default, is_active, entered_by, entered_dt)
        VALUES
            (@plan_id, @organization_id,
             -- plan code + -P01, -P02 ... in the order created
             LEFT(@plan_code, 110) + N'-P'
               + RIGHT(N'0' + CAST((SELECT COUNT(*) + 1 FROM grac_practice.org_assurance_plan_programme x
                                     WHERE x.org_assurance_plan_id = @plan_id) AS NVARCHAR(10)), 2),
             LTRIM(RTRIM(@programme_name)), @objective,
             @planning_methodology_id, @m_code, @m_name,
             @owner_role_id, @owner_role_name, @owner_employee_id, @owner_display_name,
             ISNULL(@display_order, (SELECT ISNULL(MAX(x.display_order), 0) + 1
                                       FROM grac_practice.org_assurance_plan_programme x
                                      WHERE x.org_assurance_plan_id = @plan_id AND x.is_active = 1)),
             0, 1, @actor, SYSUTCDATETIME());
        SET @programme_id_out = SCOPE_IDENTITY();
    END
    ELSE
    BEGIN
        IF NOT EXISTS (SELECT 1 FROM grac_practice.org_assurance_plan_programme
                        WHERE org_assurance_programme_id = @programme_id
                          AND org_assurance_plan_id = @plan_id AND is_active = 1)
        BEGIN ROLLBACK; THROW 53944, 'The programme is not part of this plan.', 1; END

        UPDATE grac_practice.org_assurance_plan_programme
           SET programme_name          = LTRIM(RTRIM(@programme_name)),
               objective               = @objective,
               planning_methodology_id = @planning_methodology_id,
               methodology_code        = @m_code,
               methodology_name        = @m_name,
               owner_role_id           = @owner_role_id,
               owner_role_name         = @owner_role_name,
               owner_employee_id       = @owner_employee_id,
               owner_display_name      = @owner_display_name,
               display_order           = ISNULL(@display_order, display_order),
               updated_by              = @actor,
               updated_dt              = SYSUTCDATETIME()
         WHERE org_assurance_programme_id = @programme_id;
        SET @programme_id_out = @programme_id;
    END
    COMMIT;
END
