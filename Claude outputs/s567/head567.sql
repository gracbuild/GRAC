       SET assigned_employee_id = @assignee_employee_id, assigned_name = @name,
           assigned_by = @actor, assigned_dt = SYSUTCDATETIME(), updated_by = @actor, updated_dt = SYSUTCDATETIME()
     WHERE execution_question_id = @execution_question_id;
