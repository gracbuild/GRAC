           q.question_text         AS QuestionText,
           q.question_set_code     AS QuestionSetCode,
           q.question_set_name     AS QuestionSetName,
           q.testing_guidance      AS TestingGuidance,
           q.weight                AS Weight,
           q.is_mandatory          AS IsMandatory,
           q.expected_evidence     AS ExpectedEvidence,
           q.assigned_employee_id  AS AssignedEmployeeId,
           q.assigned_name         AS AssignedName,
           q.conclusion_code       AS ConclusionCode,
           q.conclusion_reason     AS ConclusionReason,
           q.concluded_by          AS ConcludedBy,
           q.concluded_dt          AS ConcludedDt,
           st.paper_count          AS PaperCount,
           st.approved_count       AS ApprovedCount,
           st.in_review_count      AS InReviewCount,
           st.open_count           AS OpenCount,
           st.suggested_conclusion AS SuggestedConclusion
      FROM grac_practice.org_assurance_execution_question q
     CROSS APPLY grac_practice.fn_org_assurance_wp_question_state(q.execution_question_id) st
     WHERE q.org_assurance_execution_id = @execution_id
     ORDER BY q.set_order, q.question_set_name, q.display_order, q.question_id;

    SELECT p.working_paper_id       AS WorkingPaperId,
           p.execution_question_id  AS ExecutionQuestionId,
           p.paper_no               AS PaperNo,
           p.paper_code             AS PaperCode,
           p.testing_method_code    AS TestingMethodCode,
           m.method_name            AS TestingMethodName,
           p.testing_guidance       AS TestingGuidance,
           p.procedure_performed    AS ProcedurePerformed,
           p.population             AS Population,
           p.sampling_method        AS SamplingMethod,
           p.sample_size            AS SampleSize,
           p.sample_details         AS SampleDetails,
           p.evidence_references    AS EvidenceReferences,
           p.test_result            AS TestResult,
           p.deviations             AS Deviations,
           p.auditor_comments       AS AuditorComments,
           p.conclusion             AS Conclusion,
           p.reviewer_comments      AS ReviewerComments,
           p.review_status          AS ReviewStatus,
           p.prepared_by_employee_id AS PreparedByEmployeeId,
           p.prepared_by_name       AS PreparedByName,
           p.submitted_dt           AS SubmittedDt,
           p.reviewed_by_name       AS ReviewedByName,
           p.reviewed_dt            AS ReviewedDt,
           p.approved_by_name       AS ApprovedByName,
           p.approved_dt            AS ApprovedDt,
           p.reopen_count           AS ReopenCount,
           (SELECT TOP 1 o.observation_code FROM grac_practice.org_assurance_observation o
             WHERE o.org_assurance_working_paper_id = p.working_paper_id AND o.is_active = 1
             ORDER BY o.org_assurance_observation_id DESC) AS FindingCode,
           (SELECT COUNT(*) FROM grac_practice.org_assurance_observation o
             WHERE o.org_assurance_working_paper_id = p.working_paper_id AND o.is_active = 1) AS FindingCount
      FROM grac_practice.org_assurance_working_paper p
      LEFT JOIN grac_practice.org_assurance_testing_method_master m ON m.method_code = p.testing_method_code
     WHERE p.org_assurance_execution_id = @execution_id
       AND p.is_active = 1
     ORDER BY p.execution_question_id, p.paper_no;

    -- The people a question can be given to: the lead and the engagement's
    -- active members / subject matter experts with an employee.
    SELECT DISTINCT x.EmployeeId, x.EmployeeName, x.TeamRole
      FROM (SELECT e.owner_employee_id AS EmployeeId, e.owner_display_name AS EmployeeName, N'LEAD' AS TeamRole
              FROM grac_practice.org_assurance_execution e
             WHERE e.org_assurance_execution_id = @execution_id AND e.owner_employee_id IS NOT NULL
            UNION
            SELECT t.employee_id, t.member_name, t.team_role
              FROM grac_practice.org_assurance_engagement_team t
              JOIN grac_practice.org_assurance_execution e
                   ON e.org_assurance_plan_item_id = t.org_assurance_plan_item_id
             WHERE e.org_assurance_execution_id = @execution_id
               AND t.is_active = 1 AND t.team_role IN (N'MEMBER', N'SME') AND t.employee_id IS NOT NULL) x
     ORDER BY x.EmployeeName;
END
