-- 8i. Create or change a working paper (Draft or Returned). The preparer
-- is the question's auditor, or anyone on the team when the question is
-- not given to anyone; the lead may always. A new paper takes the
-- question's testing guidance when none is given.
CREATE OR ALTER PROCEDURE grac_practice.sp_org_assurance_working_paper_save
    @organization_id       BIGINT,
    @execution_question_id BIGINT,
    @working_paper_id      BIGINT        = NULL,
    @testing_method_code   NVARCHAR(40)  = NULL,
    @testing_guidance      NVARCHAR(MAX) = NULL,
    @procedure_performed   NVARCHAR(MAX) = NULL,
    @population            NVARCHAR(MAX) = NULL,
    @sampling_method       NVARCHAR(400) = NULL,
    @sample_size           INT           = NULL,
    @sample_details        NVARCHAR(MAX) = NULL,
    @evidence_references   NVARCHAR(MAX) = NULL,
    @test_result           NVARCHAR(20)  = NULL,
    @deviations            NVARCHAR(MAX) = NULL,
    @auditor_comments      NVARCHAR(MAX) = NULL,
    @conclusion            NVARCHAR(MAX) = NULL,
    @employee_id           BIGINT,
    @actor                 NVARCHAR(100) = 'system',
    @working_paper_id_out  BIGINT OUTPUT
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;
    IF @organization_id IS NULL OR @execution_question_id IS NULL
        THROW 54009, 'organization_id and the question are required.', 1;
    IF @employee_id IS NULL
        THROW 54051, 'Sign in as an auditor of this engagement.', 1;
    SET @test_result = NULLIF(UPPER(LTRIM(RTRIM(@test_result))), N'');
    IF @test_result IS NOT NULL AND @test_result NOT IN (N'SATISFACTORY', N'PARTIAL', N'UNSATISFACTORY', N'NA')
        THROW 54062, 'The test result must be Satisfactory, Partially Satisfactory, Unsatisfactory or Not Applicable.', 1;
    SET @testing_method_code = NULLIF(LTRIM(RTRIM(@testing_method_code)), N'');
    IF @testing_method_code IS NOT NULL AND NOT EXISTS (SELECT 1 FROM grac_practice.org_assurance_testing_method_master
                                                         WHERE method_code = @testing_method_code)
        THROW 54062, 'Unknown testing method.', 1;
    IF @sample_size IS NOT NULL AND @sample_size < 0
        THROW 54062, 'The sample size cannot be negative.', 1;

    DECLARE @exec BIGINT, @status NVARCHAR(60), @assignee BIGINT, @q_code NVARCHAR(120), @q_guidance NVARCHAR(MAX),
            @exec_code NVARCHAR(120);
    SELECT @exec = q.org_assurance_execution_id, @status = s.status_code, @assignee = q.assigned_employee_id,
           @q_code = q.question_code, @q_guidance = q.testing_guidance, @exec_code = e.execution_code
      FROM grac_practice.org_assurance_execution_question q
      JOIN grac_practice.org_assurance_execution e ON e.org_assurance_execution_id = q.org_assurance_execution_id
      JOIN grac_practice.org_assurance_execution_status_master s ON s.org_assurance_execution_status_id = e.execution_status_id
     WHERE q.execution_question_id = @execution_question_id AND q.organization_id = @organization_id;
    IF @exec IS NULL THROW 54053, 'The question was not found in this organization.', 1;
    IF @status <> N'InProgress' THROW 54052, 'Working papers change while the audit is In Progress.', 1;

    DECLARE @is_lead BIT, @is_team BIT;
    SELECT @is_lead = is_lead, @is_team = is_team FROM grac_practice.fn_org_assurance_wp_roles(@exec, @employee_id);
    IF ISNULL(@is_team, 0) = 0
        THROW 54051, 'Only the engagement team prepares working papers.', 1;
    IF @is_lead = 0 AND @assignee IS NOT NULL AND @assignee <> @employee_id
        THROW 54051, 'This question is given to another auditor.', 1;

    DECLARE @cur_status NVARCHAR(20), @cur_q BIGINT, @preparer BIGINT;
    IF @working_paper_id IS NOT NULL
    BEGIN
        SELECT @cur_status = review_status, @cur_q = execution_question_id, @preparer = prepared_by_employee_id
          FROM grac_practice.org_assurance_working_paper
         WHERE working_paper_id = @working_paper_id AND organization_id = @organization_id AND is_active = 1;
        IF @cur_status IS NULL OR @cur_q <> @execution_question_id
            THROW 54053, 'The working paper was not found on this question.', 1;
        IF @cur_status NOT IN (N'Draft', N'Returned')
            THROW 54054, 'Only a Draft or Returned working paper can be changed; ask for it to be reopened.', 1;
    END

    DECLARE @name NVARCHAR(240) = (SELECT employee_name FROM grac_practice.organization_employee
                                    WHERE employee_id = @employee_id AND organization_id = @organization_id);
    BEGIN TRAN;
    IF @working_paper_id IS NULL
    BEGIN
        DECLARE @no INT = ISNULL((SELECT MAX(paper_no) FROM grac_practice.org_assurance_working_paper
                                   WHERE execution_question_id = @execution_question_id), 0) + 1;
        INSERT INTO grac_practice.org_assurance_working_paper
            (organization_id, org_assurance_execution_id, execution_question_id, paper_no, paper_code,
             testing_method_code, testing_guidance, procedure_performed, population, sampling_method,
             sample_size, sample_details, evidence_references, test_result, deviations, auditor_comments,
             conclusion, review_status, prepared_by_employee_id, prepared_by_name, entered_by)
        VALUES
            (@organization_id, @exec, @execution_question_id, @no,
             LEFT(CONCAT(@exec_code, N'-', ISNULL(@q_code, CONVERT(NVARCHAR(30), @execution_question_id)), N'-WP', @no), 160),
             @testing_method_code, ISNULL(NULLIF(@testing_guidance, N''), @q_guidance), @procedure_performed, @population,
             @sampling_method, @sample_size, @sample_details, @evidence_references, @test_result, @deviations,
             @auditor_comments, @conclusion, N'Draft', @employee_id, @name, @actor);
        SET @working_paper_id_out = SCOPE_IDENTITY();
        EXEC grac_practice.sp_org_assurance_wp_log @organization_id = @organization_id, @execution_id = @exec,
             @execution_question_id = @execution_question_id, @working_paper_id = @working_paper_id_out,
             @action_code = N'Created', @to_status = N'Draft', @employee_id = @employee_id, @actor = @actor;
    END
    ELSE
    BEGIN
        UPDATE grac_practice.org_assurance_working_paper
           SET testing_method_code = @testing_method_code, testing_guidance = @testing_guidance,
               procedure_performed = @procedure_performed, population = @population,
               sampling_method = @sampling_method, sample_size = @sample_size, sample_details = @sample_details,
               evidence_references = @evidence_references, test_result = @test_result, deviations = @deviations,
               auditor_comments = @auditor_comments, conclusion = @conclusion,
               -- a paper without a preparer (the 558 answers) takes the one who changes it
               prepared_by_employee_id = ISNULL(prepared_by_employee_id, @employee_id),
               prepared_by_name = ISNULL(prepared_by_name, @name),
               updated_by = @actor, updated_dt = SYSUTCDATETIME()
         WHERE working_paper_id = @working_paper_id;
        SET @working_paper_id_out = @working_paper_id;
        EXEC grac_practice.sp_org_assurance_wp_log @organization_id = @organization_id, @execution_id = @exec,
             @execution_question_id = @execution_question_id, @working_paper_id = @working_paper_id,
             @action_code = N'Updated', @employee_id = @employee_id, @actor = @actor;
    END
    COMMIT;
END
GO

-- 8j. Move a paper: SUBMIT (preparer / lead: Draft or Returned -> Pending;
-- the procedure, the result and the conclusion filled), REVIEW (reviewer:
-- Pending -> Reviewed), RETURN (reviewer: Pending / Reviewed -> Returned,
-- reason), APPROVE (reviewer: Pending / Reviewed -> Approved), REOPEN
-- (lead or reviewer: Approved -> Returned, reason; the question's
-- conclusion is cleared), DELETE (preparer / lead: a Draft). Nobody
-- reviews, returns or approves a paper they prepared.
CREATE OR ALTER PROCEDURE grac_practice.sp_org_assurance_working_paper_action
    @organization_id  BIGINT,
    @working_paper_id BIGINT,
    @action           NVARCHAR(20),
    @comment          NVARCHAR(MAX) = NULL,
    @employee_id      BIGINT,
    @actor            NVARCHAR(100) = 'system'
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;
    SET @action  = UPPER(LTRIM(RTRIM(@action)));
    SET @comment = NULLIF(LTRIM(RTRIM(@comment)), N'');
    IF @action NOT IN (N'SUBMIT', N'REVIEW', N'RETURN', N'APPROVE', N'REOPEN', N'DELETE')
        THROW 54062, 'Unknown working paper action.', 1;
    IF @employee_id IS NULL
        THROW 54051, 'Sign in as an auditor of this engagement.', 1;

    DECLARE @exec BIGINT, @q BIGINT, @cur NVARCHAR(20), @preparer BIGINT, @status NVARCHAR(60),
            @proc NVARCHAR(MAX), @result NVARCHAR(20), @concl NVARCHAR(MAX);
    SELECT @exec = p.org_assurance_execution_id, @q = p.execution_question_id, @cur = p.review_status,
           @preparer = p.prepared_by_employee_id, @status = s.status_code,
           @proc = p.procedure_performed, @result = p.test_result, @concl = p.conclusion
      FROM grac_practice.org_assurance_working_paper p
      JOIN grac_practice.org_assurance_execution e ON e.org_assurance_execution_id = p.org_assurance_execution_id
      JOIN grac_practice.org_assurance_execution_status_master s ON s.org_assurance_execution_status_id = e.execution_status_id
     WHERE p.working_paper_id = @working_paper_id AND p.organization_id = @organization_id AND p.is_active = 1;
    IF @exec IS NULL THROW 54053, 'The working paper was not found in this organization.', 1;
    IF @status <> N'InProgress' THROW 54052, 'Working papers change while the audit is In Progress.', 1;

    DECLARE @is_lead BIT, @is_team BIT, @is_reviewer BIT;
    SELECT @is_lead = is_lead, @is_team = is_team, @is_reviewer = is_reviewer
      FROM grac_practice.fn_org_assurance_wp_roles(@exec, @employee_id);
    DECLARE @name NVARCHAR(240) = (SELECT employee_name FROM grac_practice.organization_employee
                                    WHERE employee_id = @employee_id AND organization_id = @organization_id);
    DECLARE @to NVARCHAR(20) = CASE @action WHEN N'SUBMIT' THEN N'Pending' WHEN N'REVIEW' THEN N'Reviewed'
                                            WHEN N'RETURN' THEN N'Returned' WHEN N'APPROVE' THEN N'Approved'
                                            WHEN N'REOPEN' THEN N'Returned' ELSE @cur END;

    IF @action IN (N'SUBMIT', N'DELETE')
    BEGIN
        IF NOT (ISNULL(@is_lead, 0) = 1 OR (ISNULL(@is_team, 0) = 1 AND ISNULL(@preparer, @employee_id) = @employee_id))
            THROW 54051, 'Only the preparer or the lead auditor does this.', 1;
        IF @action = N'SUBMIT' AND @cur NOT IN (N'Draft', N'Returned')
            THROW 54054, 'Only a Draft or Returned working paper is submitted for review.', 1;
        IF @action = N'DELETE' AND @cur <> N'Draft'
            THROW 54054, 'Only a Draft working paper is deleted.', 1;
        IF @action = N'SUBMIT' AND (NULLIF(LTRIM(RTRIM(@proc)), N'') IS NULL OR @result IS NULL
                                    OR NULLIF(LTRIM(RTRIM(@concl)), N'') IS NULL)
            THROW 54055, 'Fill the procedure performed, the test result and the conclusion before submitting.', 1;
    END
    ELSE IF @action IN (N'REVIEW', N'RETURN', N'APPROVE')
    BEGIN
        IF ISNULL(@is_reviewer, 0) = 0
            THROW 54056, 'Only the engagement reviewer (or the lead auditor when there is none) reviews working papers.', 1;
        IF @preparer = @employee_id
            THROW 54056, 'You prepared this working paper; it needs another reviewer (add an Engagement Reviewer to the audit team).', 1;
        IF @cur NOT IN (N'Pending', N'Reviewed') OR (@action = N'REVIEW' AND @cur <> N'Pending')
            THROW 54054, 'The working paper is not awaiting review.', 1;
        IF @action = N'RETURN' AND @comment IS NULL
            THROW 54057, 'Say why the working paper is returned.', 1;
    END
    ELSE IF @action = N'REOPEN'
    BEGIN
        IF ISNULL(@is_lead, 0) = 0 AND ISNULL(@is_reviewer, 0) = 0
            THROW 54058, 'Only the lead auditor or the reviewer reopens a working paper.', 1;
        IF @cur <> N'Approved'
            THROW 54054, 'Only an Approved working paper is reopened.', 1;
        IF @comment IS NULL
            THROW 54057, 'Say why the working paper is reopened.', 1;
    END

    BEGIN TRAN;
    IF @action = N'DELETE'
        UPDATE grac_practice.org_assurance_working_paper
           SET is_active = 0, updated_by = @actor, updated_dt = SYSUTCDATETIME()
         WHERE working_paper_id = @working_paper_id;
    ELSE
        UPDATE grac_practice.org_assurance_working_paper
           SET review_status    = @to,
               submitted_dt     = CASE WHEN @action = N'SUBMIT' THEN SYSUTCDATETIME() ELSE submitted_dt END,
               reviewed_by_name = CASE WHEN @action IN (N'REVIEW', N'RETURN', N'APPROVE') THEN @name ELSE reviewed_by_name END,
               reviewed_dt      = CASE WHEN @action IN (N'REVIEW', N'RETURN', N'APPROVE') THEN SYSUTCDATETIME() ELSE reviewed_dt END,
               approved_by_name = CASE WHEN @action = N'APPROVE' THEN @name WHEN @action = N'REOPEN' THEN NULL ELSE approved_by_name END,
               approved_dt      = CASE WHEN @action = N'APPROVE' THEN SYSUTCDATETIME() WHEN @action = N'REOPEN' THEN NULL ELSE approved_dt END,
               reopen_count     = reopen_count + CASE WHEN @action = N'REOPEN' THEN 1 ELSE 0 END,
               -- the reviewer's challenge is kept, each with who / when
               reviewer_comments = CASE WHEN @comment IS NOT NULL AND @action IN (N'REVIEW', N'RETURN', N'APPROVE', N'REOPEN')
                                        THEN CONCAT(reviewer_comments, CASE WHEN reviewer_comments IS NULL THEN N'' ELSE NCHAR(10) END,
                                                    N'[', CONVERT(NVARCHAR(16), SYSUTCDATETIME(), 120), N' ', ISNULL(@name, @actor), N'] ', @comment)
                                        ELSE reviewer_comments END,
               updated_by = @actor, updated_dt = SYSUTCDATETIME()
         WHERE working_paper_id = @working_paper_id;

    -- A paper that leaves Approved takes its question's conclusion with it.
    IF @action = N'REOPEN'
    BEGIN
        UPDATE grac_practice.org_assurance_execution_question
           SET conclusion_code = NULL, conclusion_reason = NULL, concluded_by = NULL, concluded_dt = NULL,
               updated_by = @actor, updated_dt = SYSUTCDATETIME()
         WHERE execution_question_id = @q AND conclusion_code IS NOT NULL;
        EXEC grac_practice.sp_org_assurance_execution_score_refresh @execution_id = @exec;
    END

    -- an EXEC argument cannot be an expression: the logged state first
    DECLARE @logged_to NVARCHAR(20) = CASE WHEN @action = N'DELETE' THEN N'Deleted' ELSE @to END;
    EXEC grac_practice.sp_org_assurance_wp_log @organization_id = @organization_id, @execution_id = @exec,
         @execution_question_id = @q, @working_paper_id = @working_paper_id,
         @action_code = @action, @from_status = @cur, @to_status = @logged_to,
         @comment = @comment, @employee_id = @employee_id, @actor = @actor;
    COMMIT;
END
GO

-- 8k. Conclude a question: every paper Approved (at least one); the
-- conclusion is the suggested one (worst approved result) unless a
-- reason is given. The lead or the question's auditor concludes.
CREATE OR ALTER PROCEDURE grac_practice.sp_org_assurance_wp_question_conclude
    @organization_id       BIGINT,
    @execution_question_id BIGINT,
    @conclusion_code       NVARCHAR(20),
    @reason                NVARCHAR(2000) = NULL,
    @employee_id           BIGINT,
    @actor                 NVARCHAR(100) = 'system'
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;
    SET @conclusion_code = UPPER(NULLIF(LTRIM(RTRIM(@conclusion_code)), N''));
    SET @reason = NULLIF(LTRIM(RTRIM(@reason)), N'');
    IF @conclusion_code IS NULL OR @conclusion_code NOT IN (N'SATISFACTORY', N'PARTIAL', N'UNSATISFACTORY', N'NA')
        THROW 54062, 'The conclusion must be Satisfactory, Partially Satisfactory, Unsatisfactory or Not Applicable.', 1;
    DECLARE @exec BIGINT, @status NVARCHAR(60), @assignee BIGINT, @old NVARCHAR(20);
    SELECT @exec = q.org_assurance_execution_id, @status = s.status_code, @assignee = q.assigned_employee_id,
           @old = q.conclusion_code
      FROM grac_practice.org_assurance_execution_question q
      JOIN grac_practice.org_assurance_execution e ON e.org_assurance_execution_id = q.org_assurance_execution_id
      JOIN grac_practice.org_assurance_execution_status_master s ON s.org_assurance_execution_status_id = e.execution_status_id
     WHERE q.execution_question_id = @execution_question_id AND q.organization_id = @organization_id;
    IF @exec IS NULL THROW 54053, 'The question was not found in this organization.', 1;
    IF @status <> N'InProgress' THROW 54052, 'Working papers change while the audit is In Progress.', 1;
    IF NOT EXISTS (SELECT 1 FROM grac_practice.fn_org_assurance_wp_roles(@exec, @employee_id) r
                    WHERE r.is_lead = 1 OR (r.is_team = 1 AND @assignee = @employee_id))
        THROW 54058, 'The lead auditor or the question''s auditor concludes it.', 1;

    DECLARE @papers INT, @approved INT, @suggested NVARCHAR(20);
    SELECT @papers = paper_count, @approved = approved_count, @suggested = suggested_conclusion
      FROM grac_practice.fn_org_assurance_wp_question_state(@execution_question_id);
    IF @papers = 0 OR @approved <> @papers
        THROW 54060, 'Every working paper of the question must be approved before it is concluded.', 1;
    IF @conclusion_code <> @suggested AND @reason IS NULL
        THROW 54061, 'The conclusion differs from the approved working papers; give the reason.', 1;

    DECLARE @name NVARCHAR(240) = (SELECT employee_name FROM grac_practice.organization_employee
                                    WHERE employee_id = @employee_id AND organization_id = @organization_id);
    BEGIN TRAN;
    UPDATE grac_practice.org_assurance_execution_question
       SET conclusion_code = @conclusion_code,
           conclusion_reason = CASE WHEN @conclusion_code = @suggested THEN NULL ELSE @reason END,
           concluded_by = ISNULL(@name, @actor), concluded_dt = SYSUTCDATETIME(),
           updated_by = @actor, updated_dt = SYSUTCDATETIME()
     WHERE execution_question_id = @execution_question_id;
    EXEC grac_practice.sp_org_assurance_execution_score_refresh @execution_id = @exec;
    EXEC grac_practice.sp_org_assurance_wp_log @organization_id = @organization_id, @execution_id = @exec,
         @execution_question_id = @execution_question_id, @action_code = N'Concluded',
         @from_status = @old, @to_status = @conclusion_code, @comment = @reason,
         @employee_id = @employee_id, @actor = @actor;
    COMMIT;
END
GO

-- 8l. The overall audit conclusion (the lead, while In Progress).
CREATE OR ALTER PROCEDURE grac_practice.sp_org_assurance_execution_conclusion_save
    @organization_id BIGINT,
    @execution_id    BIGINT,
    @conclusion      NVARCHAR(MAX),
    @employee_id     BIGINT,
    @actor           NVARCHAR(100) = 'system'
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;
    DECLARE @status NVARCHAR(60);
    SELECT @status = s.status_code
      FROM grac_practice.org_assurance_execution e
      JOIN grac_practice.org_assurance_execution_status_master s ON s.org_assurance_execution_status_id = e.execution_status_id
     WHERE e.org_assurance_execution_id = @execution_id AND e.organization_id = @organization_id AND e.is_active = 1;
    IF @status IS NULL THROW 54010, 'Execution not found or not accessible in this organization.', 1;
    IF @status <> N'InProgress' THROW 54052, 'The audit conclusion changes while the audit is In Progress.', 1;
    IF NOT EXISTS (SELECT 1 FROM grac_practice.fn_org_assurance_wp_roles(@execution_id, @employee_id) WHERE is_lead = 1)
        THROW 54058, 'Only the lead auditor writes the audit conclusion.', 1;
    DECLARE @name NVARCHAR(240) = (SELECT employee_name FROM grac_practice.organization_employee
                                    WHERE employee_id = @employee_id AND organization_id = @organization_id);
    BEGIN TRAN;
    UPDATE grac_practice.org_assurance_execution
       SET audit_conclusion = NULLIF(LTRIM(RTRIM(@conclusion)), N''), conclusion_by = ISNULL(@name, @actor),
           conclusion_dt = SYSUTCDATETIME(), updated_by = @actor, updated_dt = SYSUTCDATETIME()
     WHERE org_assurance_execution_id = @execution_id;
    EXEC grac_practice.sp_org_assurance_wp_log @organization_id = @organization_id, @execution_id = @execution_id,
         @action_code = N'AuditConclusion', @employee_id = @employee_id, @actor = @actor;
    COMMIT;
END
