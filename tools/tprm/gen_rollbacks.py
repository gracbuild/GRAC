"""Generates the 486-490 TPRM rollback scripts from the objects each
migration creates (so a new procedure can never be forgotten)."""
import re, os
DB = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'database')

def objects(num):
    f = [x for x in os.listdir(DB) if x.startswith(str(num) + '_') and 'rollback' not in x][0]
    t = open(os.path.join(DB, f)).read()
    procs = re.findall(r'CREATE OR ALTER PROCEDURE grac_practice\.(\w+)', t)
    funcs = re.findall(r'CREATE OR ALTER FUNCTION grac_practice\.(\w+)', t)
    tables = re.findall(r'CREATE TABLE grac_practice\.(\w+)', t)
    return f, procs, funcs, tables

def drops(procs, funcs):
    out = []
    for p in reversed(procs):
        out.append(f"DROP PROCEDURE IF EXISTS grac_practice.{p};")
    for fn in reversed(funcs):
        out.append(f"DROP FUNCTION IF EXISTS grac_practice.{fn};")
    return "\n".join(out)

def table_block(tables, tag, guard_sql, keep_msg):
    names = ", ".join(f"N'{t}'" for t in tables)
    empty = "\n       AND ".join(f"NOT EXISTS (SELECT 1 FROM grac_practice.{t})" for t in tables)
    dropl = "\n        ".join(f"DROP TABLE IF EXISTS grac_practice.{t};" for t in reversed(tables))
    return f"""-- Tables: dropped only when they hold no rows{guard_sql[1]}; otherwise
-- they are kept (the procedures are gone, the data is not) and the
-- script says so. Delete the rows deliberately first to drop them.
IF OBJECT_ID('grac_practice.{tables[0]}','U') IS NOT NULL
BEGIN
    IF {guard_sql[0]}{empty}
    BEGIN
        DECLARE @fk NVARCHAR(MAX) = N'';
        SELECT @fk = @fk + N'ALTER TABLE grac_practice.' + QUOTENAME(OBJECT_NAME(fk.parent_object_id))
                         + N' DROP CONSTRAINT ' + QUOTENAME(fk.name) + N';'
        FROM sys.foreign_keys fk
        WHERE OBJECT_SCHEMA_NAME(fk.parent_object_id) = N'grac_practice'
          AND OBJECT_NAME(fk.parent_object_id) IN ({names});
        EXEC sp_executesql @fk;
        {dropl}
        PRINT '{tag} rollback: tables dropped.';
    END
    ELSE
        PRINT '{tag} rollback: {keep_msg}';
END
GO
"""

HEAD = """-- =====================================================================
-- {file}
--
-- Reverses {num} ({title}).
{what}
--
-- Turn the API / Web change off first (or deploy the previous build): the
-- TPRM screens call the procedures this drops. Roll back in reverse
-- order: 490, 489, 488, 487, 486.
-- Generated by tools/tprm/gen_rollbacks.py from the objects {num} creates.
-- SAFE TO RE-RUN. ASCII-only.
-- =====================================================================
SET NOCOUNT ON;
SET XACT_ABORT ON;
SET NOEXEC OFF;
SET ANSI_NULLS ON;
SET QUOTED_IDENTIFIER ON;
GO
"""

def write(num, body, title, what):
    f, *_ = objects(num)
    name = f.replace('.sql', '_rollback.sql')
    txt = HEAD.format(file=name, num=num, title=title, what=what) + "\n" + body + f"\nPRINT '{num} rollback complete.';\nGO\n"
    txt.encode('ascii')
    open(os.path.join(DB, name), 'w').write(txt)
    print(name, len(txt.splitlines()))

