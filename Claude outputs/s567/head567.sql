    IF @status <> N'InProgress' THROW 54052, 'Working papers change while the audit is In Progress.', 1;
    IF NOT EXISTS (SELECT 1 FROM grac_practice.fn_org_assurance_wp_roles(@exec, @employee_id) WHERE is_lead = 1)
        THROW 54058, 'Only the lead auditor gives questions to the team.', 1;
