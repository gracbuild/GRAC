-- 8e. The executions a person works on (lead / team / reviewer), or all of
-- the organization's executions past Planned (@mine = 0, read only).
CREATE OR ALTER PROCEDURE grac_practice.sp_org_assurance_wp_execution_list
    @organization_id BIGINT,
    @employee_id     BIGINT        = NULL,
    @mine            BIT           = 1,
    @status          NVARCHAR(60)  = NULL,
    @search          NVARCHAR(200) = NULL
AS
BEGIN
    SET NOCOUNT ON;
    IF @organization_id IS NULL
        THROW 54009, 'organization_id is required.', 1;
    SELECT TOP 500
           e.org_assurance_execution_id AS ExecutionId,
           e.execution_code             AS ExecutionCode,
           e.execution_name             AS ExecutionName,
           e.definition_code            AS DefinitionCode,
           e.definition_name            AS DefinitionName,
           pi.engagement_code           AS EngagementCode,
           pi.engagement_name           AS EngagementName,
           s.status_code                AS ExecutionStatusCode,
           s.status_name                AS ExecutionStatusName,
           e.owner_display_name         AS LeadAuditorName,
           r.reviewer_name              AS ReviewerName,
           r.is_lead                    AS IsLead,
           r.is_team                    AS IsTeam,
           r.is_reviewer                AS IsReviewer,
           (SELECT COUNT(*) FROM grac_practice.org_assurance_execution_question q
             WHERE q.org_assurance_execution_id = e.org_assurance_execution_id)                        AS QuestionCount,
           (SELECT COUNT(*) FROM grac_practice.org_assurance_execution_question q
             WHERE q.org_assurance_execution_id = e.org_assurance_execution_id
               AND q.conclusion_code IS NOT NULL)                                                       AS ConcludedCount,
           (SELECT COUNT(*) FROM grac_practice.org_assurance_working_paper p
             WHERE p.org_assurance_execution_id = e.org_assurance_execution_id AND p.is_active = 1
               AND p.review_status IN (N'Pending', N'Reviewed'))                                        AS AwaitingReviewCount,
           e.score_pct                  AS ScorePct,
           e.score_band_name            AS ScoreBandName,
           e.planned_start_dt           AS PlannedStart,
           e.planned_end_dt             AS PlannedEnd
      FROM grac_practice.org_assurance_execution e
      JOIN grac_practice.org_assurance_execution_status_master s
           ON s.org_assurance_execution_status_id = e.execution_status_id
      LEFT JOIN grac_practice.org_assurance_plan_item pi
           ON pi.org_assurance_plan_item_id = e.org_assurance_plan_item_id
     CROSS APPLY grac_practice.fn_org_assurance_wp_roles(e.org_assurance_execution_id, @employee_id) r
     WHERE e.organization_id = @organization_id
       AND e.is_active = 1
       AND s.status_code IN (N'InProgress', N'Submitted', N'Reviewed', N'Approved', N'Closed')
       AND (ISNULL(@mine, 1) = 0 OR r.is_team = 1 OR r.is_reviewer = 1)
       AND (NULLIF(@status, N'') IS NULL OR s.status_code = @status)
       AND (NULLIF(@search, N'') IS NULL
            OR e.execution_code LIKE N'%' + @search + N'%' OR e.execution_name LIKE N'%' + @search + N'%'
            OR e.definition_name LIKE N'%' + @search + N'%' OR pi.engagement_code LIKE N'%' + @search + N'%')
     ORDER BY CASE s.status_code WHEN N'InProgress' THEN 0 WHEN N'Submitted' THEN 1 ELSE 2 END,
              e.planned_start_dt, e.execution_code;
END
